//! Go backend — runtime-support library.
//!
//! The Go backend ships a fixed `kio_runtime.go` file in every emitted
//! package directory. The file holds the package-agnostic helpers the
//! per-variant emit calls into instead of inlining: the canonical `Unit`
//! value and structural carrier peels. See [`crate::backends`](super::super)
//! § Runtime-support library convention for the framework-level
//! rationale.
//!
//! Go's body is **erased** — every value flows as `interface{}` /
//! `[]any` (the JS dynamic body's shape, on a statically-typed host).
//! `interface{}` is a dynamic universal carrier. Public generic slots use
//! `Value` to prepare exact native-to-body views without inspecting opaque
//! host containers; nominal envelopes retain their access boundary inside
//! that transport. Runtime type arguments remain erased. See
//! [`ai/topics/emit.md`](../../../../ai/topics/emit.md) § Runtime model.
//!
//! The content lives here as canonical `&str` constants so it ships
//! with the kio-rs binary; [`runtime_support_content`] binds the
//! package-namespace line (the `package <ns>` clause) and everything
//! below it is byte-identical across packages. The build-side
//! dispatcher writes it under `kio_runtime.go` alongside the package's
//! `pkg.go`, `host.go`, `shapes.go`, `ffi.go`. The file is **not
//! user-modifiable** — the emitter overwrites it on every build.

/// The relative path the build-side dispatcher writes the runtime file
/// to. Mirrored in [`super::profile`]'s
/// [`super::super::RuntimeSupport::EmbeddedFile::path`] field.
///
/// **Not** underscore-prefixed (unlike Rust's `__kio_runtime.rs`): the
/// Go toolchain ignores any source file whose name begins with `_` or
/// `.` (it treats them as non-build files), so `__kio_runtime.go` would
/// silently drop out of `go build`. `kio_runtime.go` keeps the
/// internal-file intent (the `kio_` prefix) without tripping that rule.
pub const RUNTIME_SUPPORT_FILE_PATH: &str = "kio_runtime.go";

/// The canonical content of `kio_runtime.go` for a package whose
/// emitted `package` clause is `ns`. The clause is the only
/// namespace binding; everything below it is byte-identical across
/// packages, re-emitted on every build.
///
/// What lives below the binding:
///
/// - `Unit` — Go has no unit value; `struct{}` is the canonical empty.
///   Kio `()` lowers to `Unit{}`.
/// - `kioProductSlots` / `kioProductSlot` and `kioSumPayload` /
///   `kioSumInject` name the erased structural carrier walks.
///
/// `Value` keeps public abstract transport distinct from native Go shapes;
/// exact boundary conversion code owns the native views.
/// The file is package-level documented as generated; gofmt-stable.
pub fn runtime_support_content(ns: &str) -> String {
    format!("{RUNTIME_SUPPORT_HEADER}package {ns}\n{RUNTIME_SUPPORT_BODY}")
}

const RUNTIME_SUPPORT_HEADER: &str = r#"// Generated by kio — do not edit by hand.
//
// Runtime-support library for the Go backend. The kio emitter writes
// this file alongside pkg.go / host.go / shapes.go / ffi.go in
// every emitted package; it holds the package-agnostic helpers the
// package's emit calls into. The file is rewritten on every
// `kio build` — host-side edits will not survive.

"#;

const RUNTIME_SUPPORT_BODY: &str = r#"
// Unit is the Go representation of Kio's `()` (unit). Go has no unit
// value, so `struct{}` stands in; every `()` lowers to `Unit{}`.
type Unit = struct{}

// Callable has one complete value domain, including explicit Unit. The alias
// keeps nested callable signatures identical across generated packages.
type Callable[A, R any] = interface { Call(A) R }

// Func lifts a native callback. Extracting a guest's Call method is a native
// execution boundary, rather than unchanged transport of the guest value.
type Func[A, R any] func(A) R
func (f Func[A, R]) Call(argument A) R { return f(argument) }

// TypeCallable retains an executing type stage separately from value calls.
type TypeCallable[R any] = interface { Invoke() R }
type TypeFunc[R any] func() R
func (f TypeFunc[R]) Invoke() R { return f() }

// Structural built-in types let independent artifacts share the control
// protocol without sharing their private body representations.
type kioTailEntry = func(any) (bool, any, any, any, func(any) any, func(any) any)
type kioTailCapability interface { KioTail() func(any) (bool, any, any, any, func(any) any, func(any) any) }

type kioCallable[A, R any] struct { entry kioTailEntry }
func (value kioCallable[A, R]) Call(argument A) R {
	return kioNative[R](kioDrive(false, nil, value.entry, argument, nil, nil))
}
func (value kioCallable[A, R]) KioTail() func(any) (bool, any, any, any, func(any) any, func(any) any) { return value.entry }

type kioTypeCallable[R any] struct { entry kioTailEntry }
func (value kioTypeCallable[R]) Invoke() R {
	return kioNative[R](kioDrive(false, nil, value.entry, nil, nil, nil))
}
func (value kioTypeCallable[R]) KioTail() func(any) (bool, any, any, any, func(any) any, func(any) any) { return value.entry }

func kioCallableEntry[A, R any](value Callable[A, R]) kioTailEntry {
	if guest, ok := value.(kioTailCapability); ok { return guest.KioTail() }
	return func(argument any) (bool, any, any, any, func(any) any, func(any) any) {
		return true, value.Call(kioNative[A](argument)), nil, nil, nil, nil
	}
}

func kioTypeCallableEntry[R any](value TypeCallable[R]) kioTailEntry {
	if guest, ok := value.(kioTailCapability); ok { return guest.KioTail() }
	return func(_ any) (bool, any, any, any, func(any) any, func(any) any) {
		return true, value.Invoke(), nil, nil, nil, nil
	}
}

// An imported entry retains its native result codec once, not per tail hop.
type kioBoundaryEntry struct { entry kioTailEntry; result func(any) any }

type kioValueEntry func(any) kioStep
type kioTypeEntry func() kioStep

// Named entries already know their resolved parameter slots. Keep the common
// arities inline instead of building and reopening a canonical value domain.
type kioNamedArguments struct {
	first any
	second any
	rest []any
}

type kioStep struct {
	value any
	callee any
	domain any
	owner any
	invoke func(any, kioNamedArguments) kioStep
	arguments kioNamedArguments
	typeStage bool
}

func kioDone(value any) kioStep { return kioStep{value: value} }

func kioTailValue(callee any, domain any) kioStep {
	return kioStep{callee: callee, domain: domain}
}

func kioTailType(callee any) kioStep {
	return kioStep{callee: callee, typeStage: true}
}

func kioComplete(step kioStep) any {
	return kioDrive(kioAdvance(step))
}

// Only representation-result maps wait for completion. Host-supplied role
// adapters remain observable and run in the original inner-to-outer order.
func kioDrive(done bool, value, next, argument any, first, second func(any) any) any {
	var results []func(any) any
	for {
		if second != nil { results = append(results, second) }
		if first != nil { results = append(results, first) }
		if done {
			for index := len(results)-1; index >= 0; index-- { value = results[index](value) }
			return value
		}
		done, value, next, argument, first, second = next.(kioTailEntry)(argument)
	}
}

func kioExportStep(step kioStep, result func(any) any) (bool, any, any, any, func(any) any, func(any) any) {
	done, value, next, argument, first, _ := kioAdvance(step)
	if done { return true, result(value), nil, nil, nil, nil }
	return false, nil, next, argument, first, result
}

// Run private steps without entering a foreign public driver. A boundary
// transfers its exact native argument and queues its exact result conversion.
func kioAdvance(step kioStep) (bool, any, any, any, func(any) any, func(any) any) {
	for {
		if step.invoke != nil {
			step = step.invoke(step.owner, step.arguments)
		} else if step.callee == nil {
			return true, step.value, nil, nil, nil, nil
		} else if boundary, ok := step.callee.(*kioBoundaryEntry); ok {
			return false, nil, boundary.entry, step.domain, boundary.result, nil
		} else if step.typeStage {
			switch entry := step.callee.(type) {
			case kioTypeEntry:
				step = entry()
			default:
				return true, entry.(func() any)(), nil, nil, nil, nil
			}
		} else {
			switch entry := step.callee.(type) {
			case kioValueEntry:
				step = entry(step.domain)
			default:
				return true, entry.(func(any) any)(step.domain), nil, nil, nil, nil
			}
		}
	}
}

func kioApplyValue(callee any, domain any) any {
	return kioComplete(kioTailValue(callee, domain))
}

func kioApplyType(callee any) any {
	return kioComplete(kioTailType(callee))
}

// Value transports a Kio value at a polymorphic or abstract position. Its
// contents are private; typed boundary helpers prepare and recover native
// views without inspecting an opaque host container.
type Value struct {
	value any
	intoBody func(any, any) any
}

// Prepared retains an exact static index while transporting a canonical value.
type Prepared[I any] struct {
	kioPreparedIndex [0]*I
	value Value
}

// TypeStage retains one delayed type-selection stage and its native view.
// I identifies its Kio signature; H retains the package's native host bindings.
type TypeStage[I, R, H any] struct {
	kioStageIndex [0]*I
	kioStageHost [0]*H
	value Value
	host any
	result func(any, any) R
}

// Invoke executes one stage with its abstract Value interface.
func (stage TypeStage[I, R, H]) Invoke() R {
	return stage.result(stage.host, kioApplyType(stage.kioIntoBody()))
}

func (stage TypeStage[I, R, H]) kioIntoBody() any {
	return stage.value.kioIntoBody(stage.host)
}

func (stage TypeStage[I, R, H]) KioTail() func(any) (bool, any, any, any, func(any) any, func(any) any) {
	result := func(value any) any { return stage.result(stage.host, value) }
	return func(_ any) (bool, any, any, any, func(any) any, func(any) any) {
		return kioExportStep(kioTailType(stage.kioIntoBody()), result)
	}
}

// Erase transports the prepared value through an abstract host slot.
func (value Prepared[I]) Erase() Value { return value.value }

// AtomIndex identifies a native atom selected for an abstract type parameter.
type AtomIndex[T any] struct { kioAtomIndex [0]*T }
func (AtomIndex[T]) kioIndexKind_S() {}
func PrepareAtom[T any](value T) Prepared[AtomIndex[T]] {
	return Prepared[AtomIndex[T]]{value: Atom(value)}
}

type kioAtom struct { value any }

// Atom selects an opaque native value for an otherwise abstract type slot.
// Declared Kio shapes use the package's exact typed Value helpers instead.
func Atom[T any](value T) Value { return Value{value: kioAtom{value: value}} }

// NativeAtom reads an opaque atom previously supplied with Atom. It does not
// expose structural Kio data or a nominal payload.
func NativeAtom[T any](value Value) T { return kioNative[T](value.value.(kioAtom).value) }

func (value Value) kioIntoBody(host any) any {
	if value.intoBody != nil {
		return value.intoBody(host, value.value)
	}
	return value.value
}

func kioNative[T any](value any) T {
	if value == nil {
		var zero T
		return zero
	}
	return value.(T)
}

type kioSealedValue struct { value any }

func (value kioSealedValue) kioNominalPayload() any { return value.value }

// Only resolved nominal projectors and label-field eliminations call this
// operation. Public structural views never peel a nominal envelope.
func kioNominalPayload(value any) any {
	return value.(interface { kioNominalPayload() any }).kioNominalPayload()
}

func kioProductSlots(v any, arity int) []any {
	slots := make([]any, 0, arity)
	cur := v
	for i := 0; i < arity; i++ {
		if i+1 == arity {
			slots = append(slots, cur)
		} else {
			pair := cur.([]any)
			slots = append(slots, pair[0])
			cur = pair[1]
		}
	}
	return slots
}

func kioProductSlot(v any, index int, arity int) any {
	if index < 0 || index >= arity {
		panic("kio erased body: invalid product slot")
	}
	cur := v
	for i := 0; i < arity; i++ {
		if i+1 == arity {
			return cur
		}
		pair := cur.([]any)
		if i == index {
			return pair[0]
		}
		cur = pair[1]
	}
	panic("kio erased body: invalid product slot")
}

func kioSumPayload(v any, variants int) (int, any) {
	if variants <= 0 {
		panic("kio erased body: invalid sum arity")
	}
	cur := v
	for variant := 0; variant < variants-1; variant++ {
		pair := cur.([]any)
		if pair[0].(int) == 0 {
			return variant, pair[1]
		}
		cur = pair[1]
	}
	return variants - 1, cur
}

func kioSumInject(payload any, variant int, variants int) any {
	if variants <= 0 || variant < 0 || variant >= variants {
		panic("kio erased body: invalid sum variant")
	}
	acc := payload
	if variant+1 < variants {
		acc = []any{int(0), payload}
	}
	for i := 0; i < variant; i++ {
		acc = []any{int(1), acc}
	}
	return acc
}
"#;
