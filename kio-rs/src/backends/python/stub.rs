struct PreparedPythonStub<'a> {
    package: &'a Package<Routed>,
    prepared: &'a PreparedBoundaryCallableSites,
    handle: String,
    namespace: String,
    root_bindings: BTreeMap<QualifiedTypeName, String>,
    typevars: BTreeMap<String, String>,
    declaration_defs: BTreeMap<String, String>,
    shape_defs: BTreeMap<String, String>,
    typed_dict_representatives: BTreeMap<PythonTypedDictDefinition, String>,
    protocol_defs: BTreeMap<String, String>,
    stage_bases: BTreeSet<String>,
    stage_lifts: BTreeMap<String, (String, String)>,
    protocol_variances: BTreeMap<String, Vec<ProtocolPolarity>>,
    hkt_defs: BTreeMap<String, String>,
    shared_owners: BTreeMap<String, String>,
    slot_aliases: BTreeMap<String, String>,
    public_aliases: BTreeMap<String, String>,
    annotation_children: BTreeMap<String, Vec<String>>,
}

impl<'a> PreparedPythonStub<'a> {
    fn new(
        package: &'a Package<Routed>,
        prepared: &'a PreparedBoundaryCallableSites,
        handle: String,
        namespace: &str,
    ) -> Self {
        // Python 3.10's stdlib-only type-stub surface has no recognized
        // deprecation marker. Per `specs/backends/python.md` § History-only
        // generated names are not source-stable on Python, omit retained
        // roots instead of publishing them unmarked or forcing a current host
        // to select removed types.
        let root_bindings = prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
            .filter(|binding| binding.type_params().is_empty())
            .map(|binding| {
                let name = format!("KioHost_{}", exact_qtn_frame(binding.name()));
                (binding.name().clone(), name)
            })
            .collect();
        Self {
            package,
            prepared,
            handle,
            namespace: namespace.to_owned(),
            root_bindings,
            typevars: BTreeMap::new(),
            declaration_defs: BTreeMap::new(),
            shape_defs: BTreeMap::new(),
            typed_dict_representatives: BTreeMap::new(),
            protocol_defs: BTreeMap::new(),
            stage_bases: BTreeSet::new(),
            stage_lifts: BTreeMap::new(),
            protocol_variances: BTreeMap::new(),
            hkt_defs: BTreeMap::new(),
            shared_owners: BTreeMap::new(),
            slot_aliases: BTreeMap::new(),
            public_aliases: BTreeMap::new(),
            annotation_children: BTreeMap::new(),
        }
    }

    fn render(mut self) -> Result<RenderedPythonStub, EmitError> {
        self.render_callable_protocol();
        // Every output carries the same core checker module, even if its own
        // public surface does not apply a higher-kinded constructor.
        self.render_hkt_application("KioApply1_Constructor", &["KioApply1_Argument".to_owned()]);
        for binding in self.root_bindings.values().cloned().collect::<Vec<_>>() {
            self.declare_typevar(&binding);
        }
        self.render_host_type_declarations();
        self.render_public_newtype_declarations()?;
        let host = self.render_prepared_host()?;
        let handle = self.render_prepared_handle()?;
        let factory = self.render_factory();

        let mut out = String::from(PYTHON_STUB_HEADER);
        for declaration in self.typevars.values() {
            out.push_str(declaration);
            out.push('\n');
        }
        if !self.typevars.is_empty() {
            out.push('\n');
        }
        for definition in self.hkt_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.declaration_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.shape_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.protocol_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.slot_aliases.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for (source, stage) in self.stage_lifts.values() {
            if self.stage_lifts.len() > 1 {
                out.push_str("@__kio_typing__.overload\n");
            }
            out.push_str(&format!(
                "def kio_lift_stage(source: {source}, /) -> {stage}: ...\n\n"
            ));
        }
        out.push_str(&host);
        out.push('\n');
        out.push_str(&handle);
        out.push_str(&factory);
        Ok(RenderedPythonStub {
            source: out,
            stage_bases: self.stage_bases.into_iter().collect(),
            public_aliases: self.public_aliases,
            shared_owners: self.shared_owners,
        })
    }

    fn declare_typevar(&mut self, name: &str) {
        self.typevars.entry(name.to_owned()).or_insert_with(|| {
            format!(
                "{name} = __kio_typing__.TypeVar({})",
                py_string_literal(name)
            )
        });
    }

    fn render_callable_protocol(&mut self) {
        self.declare_protocol_typevar("KioFn_Arg", ProtocolPolarity::Contravariant);
        self.declare_protocol_typevar("KioFn_Result", ProtocolPolarity::Covariant);
        self.declare_typevar("KioFn_Input");
        self.declare_typevar("KioFn_Output");
        self.declare_typevar("KioResume_Output");
        self.protocol_variances.insert(
            "KioFn".to_owned(),
            vec![ProtocolPolarity::Contravariant, ProtocolPolarity::Covariant],
        );
        self.protocol_defs.insert(
            "KioFn".to_owned(),
            "class KioFn(__kio_typing__.Protocol[KioFn_Arg, KioFn_Result]):\n    def __call__(self, domain: KioFn_Arg, /) -> KioFn_Result: ...\n    def kio_step(self, domain: KioFn_Arg, transfer: KioTransfer, /) -> KioFn_Result | None: ...\n".to_owned(),
        );
        self.protocol_defs.insert("KioTransfer".to_owned(),
            "class KioTransfer(__kio_typing__.Protocol):\n    def call(self, target: KioFn[KioFn_Input, object], domain: KioFn_Input, /) -> None: ...\n    def advance(self, target: KioStage, /) -> None: ...\n".to_owned());
        self.protocol_defs.insert("KioStage".to_owned(),
            "class KioStage(__kio_typing__.Protocol):\n    def kio_step(self, transfer: KioTransfer, /) -> object: ...\n".to_owned());
        self.protocol_defs.insert("KioResume".to_owned(),
            "class KioResume(__kio_typing__.Protocol[KioFn_Arg, KioFn_Result]):\n    def __call__(self, result: KioFn_Arg, transfer: KioTransfer, /) -> KioFn_Result | None: ...\n".to_owned());
        self.protocol_defs.insert("KioResumeStage".to_owned(),
            "class KioResumeStage(__kio_typing__.Protocol[KioFn_Result]):\n    def advance(self) -> KioFn_Result: ...\n    def kio_step(self, transfer: KioTransfer, /) -> object: ...\n".to_owned());
        self.protocol_defs.insert("KioResumeCapability".to_owned(),
            "class KioResumeCapability(__kio_typing__.Protocol):\n    def call(self, target: KioFn[KioFn_Input, KioFn_Output], domain: KioFn_Input, resume: KioResume[KioFn_Output, KioResume_Output], /) -> None: ...\n    def advance(self, target: KioResumeStage[KioFn_Output], resume: KioResume[KioFn_Output, KioResume_Output], /) -> None: ...\n".to_owned());
        self.protocol_defs.insert("KioResumeTransfer".to_owned(),
            "class KioResumeTransfer(KioTransfer, __kio_typing__.Protocol):\n    @property\n    def resume(self) -> KioResumeCapability: ...\n".to_owned());
        self.protocol_defs.insert("kio_lift".to_owned(),
            "def kio_lift(body: __kio_typing__.Callable[[KioFn_Input], KioFn_Output], /) -> KioFn[KioFn_Input, KioFn_Output]: ...\n".to_owned());
        for name in [
            "KioFn",
            "KioFn_Arg",
            "KioFn_Result",
            "KioFn_Input",
            "KioFn_Output",
            "KioTransfer",
            "KioStage",
            "KioResume",
            "KioResumeStage",
            "KioResumeCapability",
            "KioResumeTransfer",
            "KioResume_Output",
        ] {
            self.shared_owners
                .insert(name.to_owned(), "core".to_owned());
        }
    }

    fn declare_protocol_typevar(&mut self, name: &str, polarity: ProtocolPolarity) {
        self.typevars.entry(name.to_owned()).or_insert_with(|| {
            let variance = match polarity {
                ProtocolPolarity::Covariant => ", covariant=True",
                ProtocolPolarity::Contravariant => ", contravariant=True",
                ProtocolPolarity::Invariant => "",
            };
            format!(
                "{name} = __kio_typing__.TypeVar({}{variance})",
                py_string_literal(name)
            )
        });
    }

    fn localize_protocol_typevars(
        &mut self,
        context: &str,
        protocol: &str,
        typevars: Vec<String>,
        include_phantom_typevars: bool,
        signatures: &mut [FnSig],
    ) -> (Vec<String>, Vec<String>, &'static str) {
        let mut seen = BTreeSet::new();
        let requested = typevars
            .into_iter()
            .filter(|typevar| seen.insert(typevar.clone()))
            .collect::<Vec<_>>();
        let uses = protocol_root_uses(&requested, signatures, &self.protocol_variances);
        let variance_diagnostic = protocol_variance_diagnostic(&uses);
        let mut locals = Vec::new();
        let mut arguments = Vec::new();
        let mut variances = Vec::new();
        let mut replacements = BTreeMap::new();
        for (index, (typevar, use_sites)) in requested.into_iter().zip(uses).enumerate() {
            let polarity = match use_sites.polarity() {
                Some(polarity) => polarity,
                // A phantom protocol parameter is safe in either direction;
                // choose covariance so Python type checkers accept the
                // declaration while the outer host still preserves every
                // exact root argument.
                None if include_phantom_typevars => ProtocolPolarity::Covariant,
                None => continue,
            };
            let local = format!("KioProtocol_{context}_B{index}");
            self.declare_protocol_typevar(&local, polarity);
            replacements.insert(typevar.clone(), local.clone());
            locals.push(local);
            arguments.push(typevar);
            variances.push(polarity);
        }
        if !replacements.is_empty() {
            for signature in signatures.iter_mut() {
                for param in &mut signature.params {
                    *param = replace_python_identifiers(param, &replacements);
                }
                signature.ret = replace_python_identifiers(&signature.ret, &replacements);
            }
        }
        if let Some(previous) = self
            .protocol_variances
            .insert(protocol.to_owned(), variances.clone())
        {
            debug_assert_eq!(previous, variances);
        }
        (locals, arguments, variance_diagnostic)
    }

    fn root_typevars(&self) -> Vec<String> {
        self.root_bindings.values().cloned().collect()
    }

    fn render_host_type_declarations(&mut self) {
        // Keep the stub live-only per `specs/backends/python.md` §
        // History-only generated names are not source-stable on Python.
        for binding in self
            .prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
        {
            if binding.type_params().is_empty() {
                continue;
            }
            let frame = exact_qtn_frame(binding.name());
            let class_name = format!("KioHostType_{frame}");
            let params = binding
                .type_params()
                .iter()
                .enumerate()
                .map(|(index, _)| format!("KioHostParam_{frame}_{index}"))
                .collect::<Vec<_>>();
            for param in &params {
                self.declare_typevar(param);
            }
            let witness =
                self.ensure_constructor_witness("Host", binding.name(), params.len(), None);
            let applied = self.render_hkt_application(&witness, &params);
            let definition = format!(
                "class {class_name}(__kio_typing__.Generic[{}]):\n{}    @classmethod\n    def from_native(cls, value: object, /) -> {applied}: ...\n    @staticmethod\n    def to_native(value: {applied}, /) -> object: ...\n",
                params.join(", "),
                stub_doc(
                    super::super::boundary_docs::host_type(self.package, binding),
                    "    "
                )
            );
            self.register_declaration_alias("HostType", binding.name(), &class_name, &params);
            self.declaration_defs.insert(class_name, definition);
        }
    }

    fn render_public_newtype_declarations(&mut self) -> Result<(), EmitError> {
        let inventory = self.prepared.public_newtypes().cloned().collect::<Vec<_>>();
        for entry in inventory {
            let frame = exact_qtn_frame(entry.name());
            let class_name = format!("KioNewtype_{frame}");
            let params = entry
                .type_params()
                .iter()
                .enumerate()
                .map(|(index, _)| format!("KioNewtypeParam_{frame}_{index}"))
                .collect::<Vec<_>>();
            for param in &params {
                self.declare_typevar(param);
            }
            let definition = if params.is_empty() {
                let roots = self.root_typevars();
                let bases = if roots.is_empty() {
                    String::new()
                } else {
                    format!("(__kio_typing__.Generic[{}])", roots.join(", "))
                };
                let applied = apply_py_type(&class_name, &roots);
                format!(
                    "class {class_name}{bases}:\n{}    def __new__(cls, value: __kio_typing__.NoReturn, /) -> {applied}: ...\n",
                    stub_doc(
                        super::super::boundary_docs::newtype(self.package, &entry),
                        "    "
                    )
                )
            } else {
                let doc = super::super::boundary_docs::newtype(self.package, &entry);
                let witness =
                    self.ensure_constructor_witness("Newtype", entry.name(), params.len(), doc);
                let applied = self.render_hkt_application(&witness, &params);
                format!("{class_name}: __kio_typing__.TypeAlias = {applied}\n")
            };
            let mut alias_params = self.root_typevars();
            alias_params.extend(params);
            self.register_declaration_alias("Newtype", entry.name(), &class_name, &alias_params);
            self.declaration_defs.insert(class_name, definition);
        }
        Ok(())
    }

    fn register_declaration_alias(
        &mut self,
        role: &str,
        name: &QualifiedTypeName,
        target: &str,
        params: &[String],
    ) {
        let identity = crate::backends::public_names::readable_public_identity(
            name.module_segments()
                .iter()
                .map(String::as_str)
                .chain([name.name()]),
        );
        let alias = format!("Kio{role}_{identity}");
        let definition = format!(
            "{alias}: __kio_typing__.TypeAlias = {}\n",
            apply_py_type(target, params)
        );
        if let Some(previous) = self.slot_aliases.insert(alias.clone(), definition.clone()) {
            assert_eq!(
                previous, definition,
                "one readable declaration alias has one exact target"
            );
        }
        if let Some(previous) = self.public_aliases.insert(alias, target.to_owned()) {
            assert_eq!(
                previous, target,
                "one readable runtime alias has one exact target"
            );
        }
    }

    fn render_prepared_host(&mut self) -> Result<String, EmitError> {
        let host_name = format!("{}Host", self.handle);
        let mut by_namespace: BTreeMap<String, Vec<PreparedBoundaryCallableSite<'_>>> =
            BTreeMap::new();
        // Execution provenance is the live-only callable gate required by
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        for site in self.prepared.sites() {
            if site.execution().is_some()
                && matches!(
                    site.site().owner(),
                    BoundaryFacadeSiteOwner::HostFunction { .. }
                )
            {
                by_namespace
                    .entry(host_module_key(&site.site().module_segments().join("/")))
                    .or_default()
                    .push(site);
            }
        }
        let mut nested = String::new();
        let mut properties = Vec::new();
        for (namespace, sites) in by_namespace {
            let nested_name = format!("_{host_name}_{namespace}");
            let mut methods = Vec::new();
            let mut needs_getattr = false;
            let mut fallback_docs = Vec::new();
            for site in sites {
                let BoundaryFacadeSiteOwner::HostFunction { name } = site.site().owner() else {
                    unreachable!()
                };
                let name = host_name_core(name);
                if is_spellable(&name) {
                    methods.push((
                        name,
                        self.render_prepared_callable(site)?,
                        super::super::boundary_docs::callable(self.package, site),
                    ));
                } else {
                    needs_getattr = true;
                    if let Some(doc) = super::super::boundary_docs::callable(self.package, site) {
                        fallback_docs.push(format!(
                            "{name}:\n{}",
                            super::super::doc::render(doc, super::super::doc::Dialect::PlainText)
                        ));
                    }
                }
            }
            let mut signatures = methods
                .iter()
                .map(|(_, signature, _)| signature.clone())
                .collect::<Vec<_>>();
            let (locals, arguments, variance_diagnostic) = self.localize_protocol_typevars(
                &format!("Host_{namespace}"),
                &nested_name,
                self.root_typevars(),
                false,
                &mut signatures,
            );
            let bases = if locals.is_empty() {
                "__kio_typing__.Protocol".to_owned()
            } else {
                format!("__kio_typing__.Protocol[{}]", locals.join(", "))
            };
            nested.push_str(&format!(
                "class {nested_name}({bases}):{variance_diagnostic}\n"
            ));
            for ((name, _, doc), signature) in methods.iter().zip(&signatures) {
                nested.push_str(&stub_method(
                    name,
                    signature,
                    stub_doc(*doc, "        ").as_str(),
                ));
                nested.push('\n');
            }
            if needs_getattr {
                nested.push_str(&stub_getattr(&fallback_docs));
            } else if signatures.is_empty() {
                nested.push_str("    ...\n");
            }
            nested.push('\n');
            properties.push((namespace, apply_py_type(&nested_name, &arguments)));
        }

        let mut members = Vec::new();
        // Retained bindings cannot become protocol obligations; see
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        let bindings = self
            .prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
            .cloned()
            .collect::<Vec<_>>();
        for binding in bindings {
            let BoundaryHostTypeBinding::Role(role) = binding.binding() else {
                continue;
            };
            if !binding.type_params().is_empty() {
                return Err(prepared_error(
                    "role-bearing Python host type has positive constructor arity",
                ));
            }
            let exact = self.root_bindings.get(binding.name()).ok_or_else(|| {
                prepared_error("role-bearing host type has no exact root binding")
            })?;
            let primitive = role_to_py_type(role);
            let frame = readable_role_adapter_identity(
                binding.name().module_segments(),
                binding.name().name(),
            )
            .unwrap_or_else(|| exact_qtn_frame(binding.name()));
            members.push((
                HostProtocolMember::Adapter(format!("KioHostIn_{frame}")),
                FnSig {
                    params: vec![exact.clone()],
                    ret: primitive.to_owned(),
                    suppress_invalid_typevar_use: false,
                },
            ));
            members.push((
                HostProtocolMember::Adapter(format!("KioHostOut_{frame}")),
                FnSig {
                    params: vec![primitive.to_owned()],
                    ret: exact.clone(),
                    suppress_invalid_typevar_use: false,
                },
            ));
        }
        for (name, ret) in properties {
            members.push((
                HostProtocolMember::Property(name),
                FnSig {
                    params: Vec::new(),
                    ret,
                    suppress_invalid_typevar_use: false,
                },
            ));
        }
        let mut signatures = members
            .iter()
            .map(|(_, signature)| signature.clone())
            .collect::<Vec<_>>();
        let (locals, arguments, variance_diagnostic) = self.localize_protocol_typevars(
            "HostRoot",
            &host_name,
            self.root_typevars(),
            true,
            &mut signatures,
        );
        debug_assert_eq!(arguments, self.root_typevars());
        let bases = if locals.is_empty() {
            "__kio_typing__.Protocol".to_owned()
        } else {
            format!("__kio_typing__.Protocol[{}]", locals.join(", "))
        };
        let mut outer = format!("class {host_name}({bases}):{variance_diagnostic}\n");
        for ((member, _), signature) in members.iter().zip(&signatures) {
            match member {
                HostProtocolMember::Adapter(name) => {
                    let [param] = signature.params.as_slice() else {
                        unreachable!("a Python role adapter has exactly one parameter")
                    };
                    outer.push_str(&format!(
                        "    def {name}(self, value: {param}, /) -> {}: ...\n",
                        signature.ret
                    ));
                }
                HostProtocolMember::Property(name) => outer.push_str(&format!(
                    "    @property\n    def {name}(self) -> {}: ...\n",
                    signature.ret
                )),
            }
        }
        if members.is_empty() {
            outer.push_str("    ...\n");
        }
        Ok(format!("{nested}{outer}"))
    }

    fn render_prepared_handle(&mut self) -> Result<String, EmitError> {
        let mut tree = PreparedSurfaceTree::default();
        for entry in self.prepared.public_newtypes() {
            let mut path = python_facade_module_path(entry.name().module_segments());
            path.push(FacadeSelector::Type(entry.name().name().to_owned()).facade_name(false));
            tree.insert(
                &path,
                PreparedSurfaceNode::Interior(PreparedSurfaceTree::default()),
            );
        }
        // Only executable (live) sites enter the current handle; see
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        for site in self
            .prepared
            .sites()
            .filter(|site| site.execution().is_some())
        {
            let mut path = python_facade_module_path(site.site().module_segments());
            match site.site().owner() {
                BoundaryFacadeSiteOwner::HostFunction { .. } => continue,
                BoundaryFacadeSiteOwner::ExportedFunction { name } => {
                    path.push(host_name_core(name))
                }
                BoundaryFacadeSiteOwner::NewtypeConstructor { newtype, member }
                | BoundaryFacadeSiteOwner::NewtypeProjector { newtype, member } => {
                    path.push(FacadeSelector::Type(newtype.clone()).facade_name(false));
                    path.push(host_name_core(member));
                }
            }
            tree.insert(
                &path,
                PreparedSurfaceNode::Fn(
                    self.render_prepared_callable(site)?,
                    super::super::boundary_docs::callable(self.package, site).map(|doc| {
                        super::super::doc::render(doc, super::super::doc::Dialect::PlainText)
                    }),
                ),
            );
        }
        let mut out = String::new();
        self.render_prepared_tree(&tree, &self.handle.clone(), &[], &mut out);
        Ok(out)
    }

    fn render_prepared_tree(
        &self,
        tree: &PreparedSurfaceTree,
        class_name: &str,
        path: &[String],
        out: &mut String,
    ) {
        let roots = self.root_typevars();
        let mut members = Vec::new();
        let mut needs_getattr = false;
        let mut fallback_docs = Vec::new();
        for (segment, child) in &tree.entries {
            match child {
                PreparedSurfaceNode::Interior(children) => {
                    let mut child_path = path.to_vec();
                    child_path.push(segment.clone());
                    let child_name = format!(
                        "_{}_{}",
                        self.handle,
                        child_path
                            .iter()
                            .map(|part| encode_python_source(part))
                            .collect::<Vec<_>>()
                            .join("_")
                    );
                    self.render_prepared_tree(children, &child_name, &child_path, out);
                    if is_spellable(segment) {
                        members.push(format!(
                            "    {segment}: {}",
                            apply_py_type(&child_name, &roots)
                        ));
                    } else {
                        needs_getattr = true;
                    }
                }
                PreparedSurfaceNode::Fn(sig, doc) => {
                    if is_spellable(segment) {
                        let framed = doc
                            .as_deref()
                            .map(|body| stub_body_doc(body, "        "))
                            .unwrap_or_default();
                        members.push(stub_method(segment, sig, &framed));
                    } else {
                        needs_getattr = true;
                        if let Some(doc) = doc {
                            fallback_docs.push(format!("{segment}:\n{doc}"));
                        }
                    }
                }
            }
        }
        let bases = if roots.is_empty() {
            String::new()
        } else {
            format!("(__kio_typing__.Generic[{}])", roots.join(", "))
        };
        out.push_str(&format!("class {class_name}{bases}:\n"));
        if members.is_empty() && !needs_getattr {
            out.push_str("    ...\n");
        } else {
            for member in members {
                out.push_str(&member);
                out.push('\n');
            }
            if needs_getattr {
                out.push_str(&stub_getattr(&fallback_docs));
            }
        }
        out.push('\n');
    }

    fn render_factory(&self) -> String {
        let roots = self.root_typevars();
        let host_name = apply_py_type(&format!("{}Host", self.handle), &roots);
        let handle = apply_py_type(&self.handle, &roots);
        // Current-host construction depends only on live execution sites and
        // live role bindings; see the Python history-omission contract in
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        let host_required = self.prepared.sites().any(|site| {
            site.execution().is_some()
                && matches!(
                    site.site().owner(),
                    BoundaryFacadeSiteOwner::HostFunction { .. }
                )
        }) || self.prepared.host_bindings().any(|binding| {
            matches!(binding.binding(), BoundaryHostTypeBinding::Role(_))
                && matches!(binding.origin(), BoundaryHostBindingOrigin::Live)
                && binding.type_params().is_empty()
        });
        if host_required {
            format!(
                "def create_{}(host: {host_name}) -> {handle}: ...\n",
                crate::backends::namespace::value_brand(&self.namespace)
            )
        } else {
            format!(
                "def create_{}(host: {host_name} | None = None) -> {handle}: ...\n",
                crate::backends::namespace::value_brand(&self.namespace)
            )
        }
    }

    fn render_prepared_callable(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
    ) -> Result<FnSig, EmitError> {
        let execution_layout = site
            .execution()
            .ok_or_else(|| prepared_error("Python callable has no live execution layout"))?;
        let entry = site.plan().entry();
        let context = exact_site_frame(site);
        let alias = readable_site_alias(site);
        let mut scope = PythonFacadeScope::default();
        let mut params = Vec::new();
        let mut method_typevars = Vec::new();
        for (stage_index, (semantic, execution)) in entry
            .head_stages
            .iter()
            .zip(execution_layout.head_stages())
            .enumerate()
        {
            match (semantic, execution) {
                (
                    BoundaryCallableHeadStage::Type { id, .. },
                    CallableExecutionStage::Type { .. },
                ) => {
                    let name = format!("KioType_{context}_B{}", id.index());
                    self.declare_typevar(&name);
                    scope.bind(*id, name.clone());
                    method_typevars.push(name);
                }
                (
                    BoundaryCallableHeadStage::Value { slots },
                    CallableExecutionStage::Value(layout),
                ) => {
                    let parameters = self.render_callable_params(
                        site.plan().value_plan(),
                        slots,
                        layout,
                        site.nominals(),
                        &scope,
                        &format!("{context}_H{stage_index}"),
                    )?;
                    for parameter in parameters {
                        self.record_slot_alias(&format!("{alias}_Arg{}", params.len()), &parameter);
                        params.push(parameter);
                    }
                }
                _ => {
                    return Err(prepared_error(
                        "Python callable head disagrees with its execution layout",
                    ));
                }
            }
        }
        let ret = self.render_value_use(
            site.plan().value_plan(),
            site.plan().value_plan().source(entry.returned),
            site.nominals(),
            &scope,
            &context,
        )?;
        self.record_slot_alias(&format!("{alias}_Result"), &ret);
        let suppress_invalid_typevar_use = method_typevars.iter().any(|typevar| {
            params
                .iter()
                .chain(std::iter::once(&ret))
                .map(|annotation| python_identifier_occurrences(annotation, typevar))
                .sum::<usize>()
                == 1
        });
        Ok(FnSig {
            params,
            ret,
            suppress_invalid_typevar_use,
        })
    }

    fn render_callable_params(
        &mut self,
        values: &ValuePlan,
        slots: &[FacadeUseId],
        layout: &CallableValueStageLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
    ) -> Result<Vec<String>, EmitError> {
        let mut params = Vec::new();
        for (source_index, source) in layout.source_params().iter().enumerate() {
            let mut product_index = 0;
            let parameter = values.native_parameter_domain(source, slots, |step| match step {
                ValueDomainStep::Value(id) => {
                    self.render_value_use(values, id, nominals, scope, context)
                }
                ValueDomainStep::Product(left, right) => {
                    let name = format!("KioShape_{context}_P{source_index}_R{product_index}");
                    product_index += 1;
                    Ok(self.synth_typed_dict(
                        &name,
                        &[("left".to_owned(), left), ("right".to_owned(), right)],
                        scope,
                    ))
                }
            })?;
            if let Some(parameter) = parameter {
                params.push(parameter);
            }
        }
        Ok(params)
    }

    fn render_value_use(
        &mut self,
        values: &ValuePlan,
        use_id: ValueUseId,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
    ) -> Result<String, EmitError> {
        use std::rc::Rc;
        #[derive(Clone)]
        enum Plan<'a> {
            Source(&'a ValuePlan),
            Stage(Rc<ValuePlan>, String),
        }
        impl Plan<'_> {
            fn value(&self) -> &ValuePlan {
                match self {
                    Self::Source(plan) => plan,
                    Self::Stage(plan, _) => plan,
                }
            }
        }
        enum Task<'a> {
            Enter(Plan<'a>, ValueUseId, Rc<PythonFacadeScope>, Rc<str>),
            Finish(Plan<'a>, ValueUseId, Rc<PythonFacadeScope>, Rc<str>, usize),
            Application(usize),
            Captures(Rc<ValuePlan>, String, usize),
            Stage(String, Vec<String>, String),
        }

        // Structural width and nested type stages both use the heap worklist.
        let mut pending = vec![Task::Enter(
            Plan::Source(values),
            use_id,
            Rc::new(scope.clone()),
            Rc::from(context),
        )];
        let mut rendered = Vec::<String>::new();
        while let Some(task) = pending.pop() {
            match task {
                Task::Enter(plan, id, scope, context) => {
                    let values = plan.value();
                    if matches!(values.use_at(id), ValueUse::Forall { .. }) {
                        let shape = values.stage_shape(id, |name| {
                            nominals
                                .declaration(name)
                                .map(BoundaryNominalDeclaration::kind)
                                .ok_or_else(|| {
                                    prepared_error(
                                        "a Python stage capture omitted its nominal kind",
                                    )
                                })
                        })?;
                        let identity = shape
                            .plan
                            .identity(shape.plan.root(), shape.plan.ambient_binders());
                        let protocol = super::super::value_plan::canonical_stage_symbol(&identity);
                        pending.push(Task::Captures(
                            Rc::new(shape.plan),
                            protocol,
                            shape.captures.len(),
                        ));
                        for capture in shape.captures.into_iter().rev() {
                            match capture {
                                ValueCapture::Use(child) => pending.push(Task::Enter(
                                    plan.clone(),
                                    child,
                                    Rc::clone(&scope),
                                    Rc::clone(&context),
                                )),
                                ValueCapture::ApplicationPrefix { constructor, args } => {
                                    pending.push(Task::Application(args.len()));
                                    for arg in args.into_iter().rev() {
                                        pending.push(Task::Enter(
                                            plan.clone(),
                                            arg,
                                            Rc::clone(&scope),
                                            Rc::clone(&context),
                                        ));
                                    }
                                    pending.push(Task::Enter(
                                        plan.clone(),
                                        constructor,
                                        Rc::clone(&scope),
                                        Rc::clone(&context),
                                    ));
                                }
                            }
                        }
                        continue;
                    }
                    let mut children = Vec::new();
                    match values.use_at(id) {
                        ValueUse::Apply { constructor, args } => {
                            children.push(*constructor);
                            children.extend(args);
                        }
                        ValueUse::Product { left, right } | ValueUse::Sum { left, right } => {
                            children.extend([*left, *right]);
                        }
                        ValueUse::Function { domain, result, .. } => {
                            children.extend([*domain, *result]);
                        }
                        ValueUse::Forall { .. } => {
                            unreachable!("type stages use their shared shape")
                        }
                        ValueUse::Unit
                        | ValueUse::Bottom
                        | ValueUse::Bound(_)
                        | ValueUse::Nominal(_) => {}
                    }
                    pending.push(Task::Finish(
                        plan.clone(),
                        id,
                        Rc::clone(&scope),
                        Rc::clone(&context),
                        children.len(),
                    ));
                    pending.extend(children.into_iter().rev().map(|child| {
                        Task::Enter(plan.clone(), child, Rc::clone(&scope), Rc::clone(&context))
                    }));
                }
                Task::Finish(plan, id, scope, context, count) => {
                    let children = rendered.split_off(rendered.len() - count);
                    let owner = match &plan {
                        Plan::Source(_) => None,
                        Plan::Stage(_, owner) => Some(owner.as_str()),
                    };
                    let result = match plan.value().use_at(id) {
                        ValueUse::Unit => "None".to_owned(),
                        ValueUse::Bottom => "__kio_typing__.NoReturn".to_owned(),
                        ValueUse::Bound(binder) => scope.lookup(*binder)?.to_owned(),
                        ValueUse::Nominal(name) => self.render_value_nominal(name, nominals)?,
                        ValueUse::Apply { .. } => {
                            let (head, args) = children
                                .split_first()
                                .expect("an application has its constructor");
                            self.render_hkt_application(head, args)
                        }
                        ValueUse::Product { .. } => self.synth_owned_typed_dict(
                            &format!("KioShape_{context}_U{}", id.index()),
                            &[
                                ("left".to_owned(), children[0].clone()),
                                ("right".to_owned(), children[1].clone()),
                            ],
                            &scope,
                            owner,
                        ),
                        ValueUse::Sum { .. } => {
                            let mut arms = Vec::new();
                            for (tag, child) in ["left", "right"].into_iter().zip(children) {
                                arms.push(self.synth_owned_typed_dict(
                                    &format!("KioShape_{context}_U{}_{tag}", id.index()),
                                    &[
                                        (
                                            "tag".to_owned(),
                                            format!("__kio_typing__.Literal['{tag}']"),
                                        ),
                                        ("value".to_owned(), child),
                                    ],
                                    &scope,
                                    owner,
                                ));
                            }
                            arms.join(" | ")
                        }
                        ValueUse::Function { .. } => {
                            format!("KioFn[{}, {}]", children[0], children[1])
                        }
                        ValueUse::Forall { .. } => {
                            unreachable!("type stages use their shared shape")
                        }
                    };
                    rendered.push(result);
                }
                Task::Application(count) => {
                    let children = rendered.split_off(rendered.len() - count - 1);
                    rendered.push(self.render_hkt_application(&children[0], &children[1..]));
                }
                Task::Captures(plan, protocol, count) => {
                    let arguments = rendered.split_off(rendered.len() - count);
                    let applied = apply_py_type(&protocol, &arguments);
                    if self.protocol_defs.contains_key(&protocol) {
                        rendered.push(applied);
                        continue;
                    }
                    let mut scope = PythonFacadeScope::default();
                    let mut locals = Vec::new();
                    for (index, binder) in plan.ambient_binders().iter().enumerate() {
                        let local = format!("{protocol}_C{index}");
                        self.shared_owners.insert(local.clone(), protocol.clone());
                        scope.bind(*binder, local.clone());
                        locals.push(local);
                    }
                    let ValueUse::Forall { binder, result } = plan.use_at(plan.root()) else {
                        unreachable!("a stage shape preserves its leading type binder")
                    };
                    let selected = format!("{protocol}_Selected");
                    self.declare_typevar(&selected);
                    self.shared_owners
                        .insert(selected.clone(), protocol.clone());
                    scope.bind(*binder, selected);
                    let result = *result;
                    let context = Rc::from(format!("Stage_{protocol}"));
                    pending.push(Task::Stage(protocol.clone(), locals, applied));
                    pending.push(Task::Enter(
                        Plan::Stage(plan, protocol),
                        result,
                        Rc::new(scope),
                        context,
                    ));
                }
                Task::Stage(protocol, locals, applied) => {
                    let ret = rendered.pop().expect("a type stage has its result");
                    self.render_stage_protocol(&protocol, &locals, &ret);
                    rendered.push(applied);
                }
            }
        }
        assert_eq!(rendered.len(), 1, "one Python value root is rendered");
        Ok(rendered.pop().expect("one rendered Python value"))
    }

    fn render_value_nominal(
        &mut self,
        name: &QualifiedTypeName,
        nominals: &BoundaryNominalDependencies,
    ) -> Result<String, EmitError> {
        let declaration = nominals.declaration(name).ok_or_else(|| {
            prepared_error("Python value plan omitted an exact nominal dependency")
        })?;
        match declaration {
            BoundaryNominalDeclaration::HostType { type_params, .. } => {
                if type_params.is_empty() {
                    self.root_bindings
                        .get(name)
                        .cloned()
                        .ok_or_else(|| prepared_error("exact Python host binding is absent"))
                } else {
                    Ok(self.ensure_constructor_witness("Host", name, type_params.len(), None))
                }
            }
            BoundaryNominalDeclaration::Newtype { type_params, .. } => {
                if type_params.is_empty() {
                    Ok(apply_py_type(
                        &format!("KioNewtype_{}", exact_qtn_frame(name)),
                        &self.root_typevars(),
                    ))
                } else {
                    Ok(self.ensure_constructor_witness("Newtype", name, type_params.len(), None))
                }
            }
        }
    }

    fn ensure_constructor_witness(
        &mut self,
        category: &str,
        name: &QualifiedTypeName,
        arity: usize,
        doc: Option<&crate::ast::DocComment>,
    ) -> String {
        let witness = format!("Kio{category}Mk_{}", exact_qtn_frame(name));
        let roots = if category == "Newtype" {
            self.root_typevars()
        } else {
            Vec::new()
        };
        self.hkt_defs.entry(witness.clone()).or_insert_with(|| {
            let bases = if roots.is_empty() {
                String::new()
            } else {
                format!("(__kio_typing__.Generic[{}])", roots.join(", "))
            };
            format!(
                "class {witness}{bases}:\n{}    # Exact arity-{arity} constructor index for every application stage.\n    ...\n",
                stub_doc(doc, "    ")
            )
        });
        self.register_declaration_alias(&format!("{category}Mk"), name, &witness, &roots);
        apply_py_type(&witness, &roots)
    }

    fn render_hkt_application(&mut self, head: &str, args: &[String]) -> String {
        if args.is_empty() {
            return head.to_owned();
        }
        let name = "KioApply1";
        if !self.hkt_defs.contains_key(name) {
            self.declare_typevar("KioApply1_Constructor");
            self.declare_typevar("KioApply1_Argument");
            self.hkt_defs.insert(name.to_owned(),
                "class KioApply1(__kio_typing__.Generic[KioApply1_Constructor, KioApply1_Argument]):\n    def __new__(cls, value: __kio_typing__.NoReturn, /) -> KioApply1[KioApply1_Constructor, KioApply1_Argument]: ...\n".to_owned());
            for name in ["KioApply1", "KioApply1_Constructor", "KioApply1_Argument"] {
                self.shared_owners
                    .insert(name.to_owned(), "core".to_owned());
            }
        }
        args.iter().fold(head.to_owned(), |head, arg| {
            format!("{name}[{head}, {arg}]")
        })
    }

    fn render_stage_protocol(&mut self, protocol: &str, locals: &[String], ret: &str) {
        // Nested stages finish first, so their declared polarity composes
        // through advance's result without another value-plan traversal.
        let uses = protocol_root_uses(
            locals,
            &[FnSig {
                params: Vec::new(),
                ret: ret.to_owned(),
                suppress_invalid_typevar_use: false,
            }],
            &self.protocol_variances,
        );
        let variance_diagnostic = protocol_variance_diagnostic(&uses);
        let variances = uses
            .into_iter()
            .map(|uses| uses.polarity().unwrap_or(ProtocolPolarity::Covariant))
            .collect::<Vec<_>>();
        for (local, variance) in locals.iter().zip(&variances) {
            self.declare_protocol_typevar(local, *variance);
        }
        let applied = apply_py_type(protocol, locals);
        let source = format!("{protocol}Source");
        let applied_source = apply_py_type(&source, locals);
        for name in [protocol.to_owned(), source.clone()] {
            self.shared_owners.insert(name, protocol.to_owned());
        }
        self.annotation_children
            .insert(protocol.to_owned(), vec![ret.to_owned()]);
        let protocol_base = if locals.is_empty() {
            "__kio_typing__.Protocol".to_owned()
        } else {
            format!("__kio_typing__.Protocol[{}]", locals.join(", "))
        };
        let source_base = if locals.is_empty() {
            String::new()
        } else {
            format!("(__kio_typing__.Generic[{}])", locals.join(", "))
        };
        self.protocol_defs.insert(source, format!(
            "class {protocol}Source{source_base}:\n    def advance(self) -> {ret}: ...  # pyright: ignore[reportInvalidTypeVarUse]\n"
        ));
        self.protocol_defs.insert(protocol.to_owned(), format!(
            "class {protocol}({protocol_base}):{variance_diagnostic}\n    def advance(self) -> {ret}: ...  # pyright: ignore[reportInvalidTypeVarUse]\n    def kio_step(self, transfer: KioTransfer, /) -> object: ...\n"
        ));
        self.stage_lifts
            .insert(protocol.to_owned(), (applied_source, applied));
        self.protocol_variances
            .insert(protocol.to_owned(), variances);
        self.stage_bases.insert(protocol.to_owned());
    }

    fn synth_typed_dict(
        &mut self,
        name: &str,
        fields: &[(String, String)],
        scope: &PythonFacadeScope,
    ) -> String {
        self.synth_owned_typed_dict(name, fields, scope, None)
    }

    fn synth_owned_typed_dict(
        &mut self,
        name: &str,
        fields: &[(String, String)],
        scope: &PythonFacadeScope,
        owner: Option<&str>,
    ) -> String {
        self.annotation_children.insert(
            name.to_owned(),
            fields.iter().map(|(_, ty)| ty.clone()).collect(),
        );
        if let Some(owner) = owner {
            self.shared_owners.insert(name.to_owned(), owner.to_owned());
        }
        let definition_cached = self.shape_defs.contains_key(name);
        let mut params = self.root_typevars();
        params.extend(scope.binders.values().cloned());
        let params = select_live_python_identifiers(
            params,
            fields.iter().map(|(_, annotation)| annotation.as_str()),
        );
        if !definition_cached {
            let all_identifiers = fields.iter().all(|(key, _)| is_plain_identifier(key));
            let definition = if all_identifiers {
                let key = PythonTypedDictDefinition {
                    owner: owner.map(str::to_owned),
                    params: params.clone(),
                    fields: fields.to_vec(),
                };
                if let Some(representative) = self.typed_dict_representatives.get(&key) {
                    // TypedDicts are structural. Keep each site's public name,
                    // but make the checker elaborate an identical body once.
                    // Exact annotation and binder spellings avoid unfolding
                    // recursive types or identifying distinct generic scopes.
                    let definition = format!(
                        "{name}: __kio_typing__.TypeAlias = {}\n",
                        apply_py_type(representative, &params)
                    );
                    self.shape_defs.insert(name.to_owned(), definition);
                    return apply_py_type(name, &params);
                }
                self.typed_dict_representatives.insert(key, name.to_owned());
                let bases = if params.is_empty() {
                    "__kio_typing__.TypedDict".to_owned()
                } else {
                    format!(
                        "__kio_typing__.TypedDict, __kio_typing__.Generic[{}]",
                        params.join(", ")
                    )
                };
                let body = fields
                    .iter()
                    .map(|(key, ty)| format!("    {key}: {ty}\n"))
                    .collect::<String>();
                format!("class {name}({bases}):\n{body}")
            } else {
                let base = format!("_{name}Fields");
                let entries = fields
                    .iter()
                    .map(|(key, ty)| format!("{}: {ty}", py_string_literal(key)))
                    .collect::<Vec<_>>()
                    .join(", ");
                if params.is_empty() {
                    format!(
                        "{name} = __kio_typing__.TypedDict({}, {{{entries}}})\n",
                        py_string_literal(name)
                    )
                } else {
                    format!(
                        "{base} = __kio_typing__.TypedDict({}, {{{entries}}})\nclass {name}({base}, __kio_typing__.Generic[{}]):\n    ...\n",
                        py_string_literal(&base),
                        params.join(", ")
                    )
                }
            };
            self.shape_defs.insert(name.to_owned(), definition);
        }
        apply_py_type(name, &params)
    }

    fn record_slot_alias(&mut self, alias: &str, annotation: &str) {
        // A bare TypeVar is not a Python type alias. All compound views retain
        // the exact existing annotation and its implicitly bound parameters.
        if !self.typevars.contains_key(annotation) {
            self.slot_aliases.insert(
                alias.to_owned(),
                format!("{alias}: __kio_typing__.TypeAlias = {annotation}\n"),
            );
        }
        let head = annotation.split('[').next().unwrap_or(annotation);
        if self.stage_lifts.contains_key(head) {
            let target = replace_python_identifiers(
                annotation,
                &BTreeMap::from([(head.to_owned(), format!("{head}Source"))]),
            );
            let name = format!("{alias}Source");
            self.slot_aliases.insert(
                name.clone(),
                format!("{name}: __kio_typing__.TypeAlias = {target}\n"),
            );
            self.public_aliases.insert(name, format!("{head}Source"));
        }
        let mut pending = vec![annotation.to_owned()];
        let mut visited = BTreeSet::new();
        let mut stage_index = 0;
        while let Some(annotation) = pending.pop() {
            let mut names = Vec::new();
            visit_python_identifiers(&annotation, |name| names.push(name.to_owned()));
            let mut children = Vec::new();
            for name in names {
                if !visited.insert(name.clone()) {
                    continue;
                }
                if let Some((source, stage)) = self.stage_lifts.get(&name) {
                    let view = format!("{alias}_Stage{stage_index}");
                    stage_index += 1;
                    for (suffix, target) in [("", stage), ("Source", source)] {
                        let alias = format!("{view}{suffix}");
                        self.slot_aliases.insert(
                            alias.clone(),
                            format!("{alias}: __kio_typing__.TypeAlias = {target}\n"),
                        );
                        self.public_aliases.insert(alias, format!("{name}{suffix}"));
                    }
                }
                if let Some(dependencies) = self.annotation_children.get(&name) {
                    children.extend(dependencies.iter().cloned());
                }
            }
            pending.extend(children.into_iter().rev());
        }
    }
}

