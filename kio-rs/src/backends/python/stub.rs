#[derive(Default)]
struct PreparedSurfaceTree {
    entries: BTreeMap<String, PreparedSurfaceNode>,
}

enum PreparedSurfaceNode {
    Interior(PreparedSurfaceTree),
    Fn(FnSig, Option<String>),
}

impl PreparedSurfaceTree {
    fn insert(&mut self, path: &[String], node: PreparedSurfaceNode) {
        debug_assert!(!path.is_empty());
        if path.len() == 1 {
            assert!(self.entries.insert(path[0].clone(), node).is_none());
            return;
        }
        let entry = self
            .entries
            .entry(path[0].clone())
            .or_insert_with(|| PreparedSurfaceNode::Interior(Self::default()));
        let PreparedSurfaceNode::Interior(children) = entry else {
            unreachable!("prepared Python facade path crosses a value leaf")
        };
        children.insert(&path[1..], node);
    }
}

