struct PythonStubDeclaration {
    name: String,
    source: String,
}

fn static_family_module(owner: &str) -> String {
    if owner == "core" {
        return "core".to_owned();
    }
    crate::backends::skin::budgeted_mint_name(format!("family_{owner}"), |_| {
        Ok::<_, std::convert::Infallible>(format!(
            "family_H{}",
            crate::backends::skin::fnv1a_64_hex(owner)
        ))
    })
    .expect("static module naming is infallible")
}

fn claim_static_locator(
    locators: &mut BTreeMap<String, String>,
    module: &str,
    owner: &str,
) -> Result<(), EmitError> {
    if let Some(previous) = locators.get(module) {
        if previous != owner {
            return Err(EmitError {
                message: format!(
                    "Python static type identities have the same bounded module locator `{module}`"
                ),
            });
        }
    } else {
        locators.insert(module.to_owned(), owner.to_owned());
    }
    Ok(())
}

fn partition_python_stub(
    source: String,
    shared_owners: &BTreeMap<String, String>,
) -> Result<PythonStubPackage, EmitError> {
    use crate::backends::namespace::PYTHON_STATIC_NAMESPACE;
    let declarations = split_python_stub_declarations(&source)?;
    let declared = declarations
        .iter()
        .map(|declaration| declaration.name.as_str())
        .collect::<BTreeSet<_>>();
    let mut groups: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut locators = BTreeMap::new();
    let mut local = String::from(PYTHON_STUB_HEADER);
    for declaration in &declarations {
        if let Some(owner) = shared_owners.get(&declaration.name) {
            let module = static_family_module(owner);
            claim_static_locator(&mut locators, &module, owner)?;
            if groups
                .entry(owner.clone())
                .or_default()
                .insert(
                    declaration.name.clone(),
                    format!("{}\n", declaration.source.trim_end()),
                )
                .is_some()
            {
                return Err(prepared_error(
                    "duplicate Python static declaration identity",
                ));
            }
            let name = &declaration.name;
            local.push_str(&format!(
                "from {PYTHON_STATIC_NAMESPACE}.{module} import {name} as {name}\n"
            ));
        } else {
            local.push_str(&declaration.source);
        }
    }
    let mut package = shard_python_stub(local)?;
    for (owner, definitions) in groups {
        let mut dependencies = BTreeSet::new();
        for definition in definitions.values() {
            visit_python_identifiers(definition, |name| {
                if declared.contains(name) && !definitions.contains_key(name) {
                    dependencies.insert(name.to_owned());
                }
            });
        }
        let mut content = String::from(PYTHON_STUB_HEADER);
        for name in dependencies {
            let dependency = shared_owners.get(&name).ok_or_else(|| {
                prepared_error(
                    "a shared Python static definition depends on a package-owned declaration",
                )
            })?;
            let module = static_family_module(dependency);
            content.push_str(&format!(
                "from {PYTHON_STATIC_NAMESPACE}.{module} import {name} as {name}\n"
            ));
        }
        content.push('\n');
        for definition in definitions.values() {
            content.push_str(definition);
            content.push('\n');
        }
        let module = static_family_module(&owner);
        package
            .companions
            .insert(format!("{PYTHON_STATIC_NAMESPACE}/{module}.pyi"), content);
    }
    Ok(package)
}

pub(super) fn shard_python_stub(flat_stub: String) -> Result<PythonStubPackage, EmitError> {
    let declarations = split_python_stub_declarations(&flat_stub)?;
    let shard_count = declarations
        .len()
        .div_ceil(PYTHON_STUB_DECLARATIONS_PER_SHARD);
    let mut owners = BTreeMap::new();
    for (index, declaration) in declarations.iter().enumerate() {
        let owner = index / PYTHON_STUB_DECLARATIONS_PER_SHARD;
        if owners.insert(declaration.name.clone(), owner).is_some() {
            return Err(prepared_error(
                "typed-stub render produced a duplicate top-level declaration",
            ));
        }
    }

    let mut files = BTreeMap::new();
    let mut entrypoint = String::from(
        "# Generated by kio - do not edit by hand.\nfrom __future__ import annotations\n\n",
    );
    for shard in 0..shard_count {
        let module = python_stub_shard_module(shard);
        entrypoint.push_str(&format!("from .{module} import *\n"));

        let start = shard * PYTHON_STUB_DECLARATIONS_PER_SHARD;
        let end = declarations
            .len()
            .min(start + PYTHON_STUB_DECLARATIONS_PER_SHARD);
        let mut dependencies = BTreeSet::new();
        let rendered = declarations[start..end]
            .iter()
            .map(|declaration| {
                rewrite_python_stub_declaration(
                    &declaration.source,
                    shard,
                    &owners,
                    &mut dependencies,
                )
            })
            .collect::<String>();
        let mut content = String::from(PYTHON_STUB_HEADER);
        for dependency in dependencies {
            let dependency = python_stub_shard_module(dependency);
            content.push_str(&format!(
                "from . import {dependency} as {dependency}  # pyright: ignore[reportPrivateUsage]\n"
            ));
        }
        if !rendered.is_empty() {
            if !content.ends_with("\n\n") {
                content.push('\n');
            }
            content.push_str(&rendered);
        }
        files.insert(format!("{module}.pyi"), content);
    }
    files.insert("__init__.pyi".to_owned(), entrypoint);
    Ok(PythonStubPackage {
        files,
        companions: BTreeMap::new(),
    })
}

fn split_python_stub_declarations(
    flat_stub: &str,
) -> Result<Vec<PythonStubDeclaration>, EmitError> {
    let body = flat_stub
        .strip_prefix(PYTHON_STUB_HEADER)
        .ok_or_else(|| prepared_error("typed-stub render omitted its generated-file header"))?;
    let mut declarations = Vec::new();
    let mut current = String::new();
    for line in body.split_inclusive('\n') {
        if !line.trim().is_empty()
            && !line.starts_with(' ')
            && !line.starts_with('\t')
            && !current.trim().is_empty()
            && current.trim() != "@__kio_typing__.overload"
        {
            declarations.push(parse_python_stub_declaration(std::mem::take(&mut current))?);
        }
        current.push_str(line);
    }
    if !current.trim().is_empty() {
        declarations.push(parse_python_stub_declaration(current)?);
    }
    let mut merged: Vec<PythonStubDeclaration> = Vec::new();
    for declaration in declarations {
        if let Some(previous) = merged.last_mut()
            && previous.name == declaration.name
            && previous
                .source
                .trim_start()
                .starts_with("@__kio_typing__.overload\n")
            && declaration
                .source
                .trim_start()
                .starts_with("@__kio_typing__.overload\n")
        {
            previous.source.push_str(&declaration.source);
        } else {
            merged.push(declaration);
        }
    }
    Ok(merged)
}

fn parse_python_stub_declaration(source: String) -> Result<PythonStubDeclaration, EmitError> {
    let line = source
        .lines()
        .find(|line| !line.trim().is_empty() && !line.starts_with('@'))
        .ok_or_else(|| prepared_error("typed-stub render produced an empty declaration"))?
        .trim_start();
    if line.starts_with("from ") {
        let (_, name) = line
            .rsplit_once(" as ")
            .ok_or_else(|| prepared_error("static import omitted its exact reexport binding"))?;
        return Ok(PythonStubDeclaration {
            name: name.to_owned(),
            source,
        });
    }
    let name_source = line
        .strip_prefix("class ")
        .or_else(|| line.strip_prefix("def "))
        .unwrap_or(line);
    let name_len = name_source
        .bytes()
        .take_while(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
        .count();
    if name_len == 0 {
        return Err(prepared_error(
            "typed-stub render produced an unrecognized top-level declaration",
        ));
    }
    Ok(PythonStubDeclaration {
        name: name_source[..name_len].to_owned(),
        source,
    })
}

fn python_stub_shard_module(index: usize) -> String {
    format!("_kio_stub_{index:04}")
}

fn rewrite_python_stub_declaration(
    source: &str,
    shard: usize,
    owners: &BTreeMap<String, usize>,
    dependencies: &mut BTreeSet<usize>,
) -> String {
    source
        .split_inclusive('\n')
        .map(|line| rewrite_python_stub_line(line, shard, owners, dependencies))
        .collect()
}

fn rewrite_python_stub_line(
    line: &str,
    shard: usize,
    owners: &BTreeMap<String, usize>,
    dependencies: &mut BTreeSet<usize>,
) -> String {
    if line.starts_with("from ") {
        return line.to_owned();
    }
    let protected = python_stub_binding_range(line);
    let bytes = line.as_bytes();
    let mut rendered = String::with_capacity(line.len());
    let mut copied_through = 0;
    let mut uses_private_cross_shard_name = false;
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at] == b'#' {
            break;
        }
        if bytes[at] == b'\'' || bytes[at] == b'"' {
            let quote = bytes[at];
            at += 1;
            while at < bytes.len() {
                if bytes[at] == b'\\' {
                    at = (at + 2).min(bytes.len());
                } else if bytes[at] == quote {
                    at += 1;
                    break;
                } else {
                    at += 1;
                }
            }
            continue;
        }
        if bytes[at].is_ascii_alphabetic() || bytes[at] == b'_' {
            let start = at;
            at += 1;
            while at < bytes.len() && (bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_') {
                at += 1;
            }
            let is_binding = protected.is_some_and(|(from, to)| start >= from && at <= to);
            let is_qualified_member = start > 0 && bytes[start - 1] == b'.';
            if !is_binding
                && !is_qualified_member
                && let Some(owner) = owners.get(&line[start..at])
                && *owner != shard
            {
                dependencies.insert(*owner);
                rendered.push_str(&line[copied_through..start]);
                rendered.push_str(&python_stub_shard_module(*owner));
                rendered.push('.');
                rendered.push_str(&line[start..at]);
                copied_through = at;
                // Ignoring the private-module import makes its public attributes
                // ordinary sibling references. Only an underscore-prefixed support
                // declaration remains a private use at the annotation site itself.
                uses_private_cross_shard_name |= line[start..at].starts_with('_');
            }
        } else {
            at += 1;
        }
    }
    rendered.push_str(&line[copied_through..]);
    if uses_private_cross_shard_name {
        add_pyright_suppression(rendered, "reportPrivateUsage")
    } else {
        rendered
    }
}

fn add_pyright_suppression(mut line: String, diagnostic: &str) -> String {
    // The shard modules and some generated support declarations are deliberately
    // private. Pyright otherwise diagnoses their sibling-shard transport as a
    // public API access, so keep that exception on the exact generated line while
    // leaving its annotation and every unrelated diagnostic under strict checking.
    let newline = if line.ends_with('\n') {
        line.pop();
        "\n"
    } else {
        ""
    };
    const PREFIX: &str = "  # pyright: ignore[";
    if let Some(directive) = line.rfind(PREFIX)
        && line.ends_with(']')
    {
        let closing = line.len() - 1;
        let diagnostics = &line[directive + PREFIX.len()..closing];
        if !diagnostics.split(',').any(|item| item.trim() == diagnostic) {
            line.insert_str(closing, &format!(", {diagnostic}"));
        }
    } else {
        line.push_str(PREFIX);
        line.push_str(diagnostic);
        line.push(']');
    }
    line.push_str(newline);
    line
}

fn python_stub_binding_range(line: &str) -> Option<(usize, usize)> {
    let bytes = line.as_bytes();
    let mut at = bytes.iter().position(|byte| !byte.is_ascii_whitespace())?;
    for keyword in ["class", "def"] {
        if line[at..].starts_with(keyword)
            && bytes
                .get(at + keyword.len())
                .is_some_and(u8::is_ascii_whitespace)
        {
            at += keyword.len();
            while bytes.get(at).is_some_and(u8::is_ascii_whitespace) {
                at += 1;
            }
            let end = python_identifier_end(bytes, at);
            return (end > at).then_some((at, end));
        }
    }
    let end = python_identifier_end(bytes, at);
    if end == at {
        return None;
    }
    let mut after = end;
    while bytes.get(after).is_some_and(u8::is_ascii_whitespace) {
        after += 1;
    }
    matches!(bytes.get(after), Some(b':') | Some(b'=')).then_some((at, end))
}

fn python_identifier_end(bytes: &[u8], mut at: usize) -> usize {
    if !bytes
        .get(at)
        .is_some_and(|byte| byte.is_ascii_alphabetic() || *byte == b'_')
    {
        return at;
    }
    at += 1;
    while bytes
        .get(at)
        .is_some_and(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
    {
        at += 1;
    }
    at
}

