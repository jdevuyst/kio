#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum ProtocolPolarity {
    Covariant,
    Contravariant,
    Invariant,
}

impl ProtocolPolarity {
    fn compose(self, nested: Self) -> Self {
        match (self, nested) {
            (Self::Invariant, _) | (_, Self::Invariant) => Self::Invariant,
            (Self::Covariant, polarity) => polarity,
            (Self::Contravariant, Self::Covariant) => Self::Contravariant,
            (Self::Contravariant, Self::Contravariant) => Self::Covariant,
        }
    }
}

/// Closed syntax tree for annotations emitted by this renderer. Python checks
/// a protocol's declared variance against every nested use of its type
/// parameters, including callback arguments and generated protocol results.
/// Parsing the emitter-owned annotation grammar here lets that check compose
/// through previously declared protocol variances; an unrecognized generated
/// form fails at emission time instead of silently assigning the wrong public
/// variance. This parser never discovers callable sites, semantic slots, or
/// nominal topology; those come exclusively from the prepared boundary plan.
#[derive(Debug)]
enum PythonTypeExpr {
    Name(String),
    Apply {
        head: String,
        args: Vec<PythonTypeExpr>,
    },
    List(Vec<PythonTypeExpr>),
    Union(Vec<PythonTypeExpr>),
}

struct PythonTypeParser {
    chars: Vec<char>,
    at: usize,
}

impl PythonTypeParser {
    fn parse(source: &str) -> Result<PythonTypeExpr, String> {
        let mut parser = Self {
            chars: source.chars().collect(),
            at: 0,
        };
        let expr = parser.parse_union()?;
        parser.skip_space();
        if parser.at != parser.chars.len() {
            return Err(format!("unexpected `{}`", parser.chars[parser.at]));
        }
        Ok(expr)
    }

    fn parse_union(&mut self) -> Result<PythonTypeExpr, String> {
        let mut arms = vec![self.parse_atom()?];
        loop {
            self.skip_space();
            if !self.take('|') {
                break;
            }
            arms.push(self.parse_atom()?);
        }
        if arms.len() == 1 {
            Ok(arms.pop().expect("one Python type arm"))
        } else {
            Ok(PythonTypeExpr::Union(arms))
        }
    }

    fn parse_atom(&mut self) -> Result<PythonTypeExpr, String> {
        self.skip_space();
        if self.take('[') {
            return Ok(PythonTypeExpr::List(self.parse_items(']')?));
        }
        let start = self.at;
        while self.at < self.chars.len()
            && !matches!(self.chars[self.at], '[' | ']' | ',' | '|')
            && !self.chars[self.at].is_whitespace()
        {
            self.at += 1;
        }
        if start == self.at {
            return Err("expected a generated Python type name".to_owned());
        }
        let name = self.chars[start..self.at].iter().collect::<String>();
        self.skip_space();
        if self.take('[') {
            Ok(PythonTypeExpr::Apply {
                head: name,
                args: self.parse_items(']')?,
            })
        } else {
            Ok(PythonTypeExpr::Name(name))
        }
    }

    fn parse_items(&mut self, close: char) -> Result<Vec<PythonTypeExpr>, String> {
        let mut items = Vec::new();
        self.skip_space();
        if self.take(close) {
            return Ok(items);
        }
        loop {
            items.push(self.parse_union()?);
            self.skip_space();
            if self.take(close) {
                return Ok(items);
            }
            if !self.take(',') {
                return Err(format!("expected `,` or `{close}`"));
            }
        }
    }

    fn skip_space(&mut self) {
        while self.at < self.chars.len() && self.chars[self.at].is_whitespace() {
            self.at += 1;
        }
    }

    fn take(&mut self, expected: char) -> bool {
        if self.chars.get(self.at) == Some(&expected) {
            self.at += 1;
            true
        } else {
            false
        }
    }
}

fn protocol_root_uses(
    roots: &[String],
    signatures: &[FnSig],
    protocol_variances: &BTreeMap<String, Vec<ProtocolPolarity>>,
) -> Vec<ProtocolRootUse> {
    if roots.is_empty() {
        return Vec::new();
    }
    let root_indices = roots
        .iter()
        .enumerate()
        .map(|(index, root)| (root.as_str(), index))
        .collect::<BTreeMap<_, _>>();
    let mut uses = vec![ProtocolRootUse::default(); roots.len()];
    for signature in signatures {
        for param in &signature.params {
            #[cfg(test)]
            record_python_stub_batch_work(|work| {
                work.protocol_annotation_parses += 1;
            });
            let expr = PythonTypeParser::parse(param).unwrap_or_else(|error| {
                panic!("generated Python parameter type `{param}` did not parse: {error}")
            });
            collect_protocol_root_uses(
                &expr,
                &root_indices,
                ProtocolPolarity::Contravariant,
                false,
                protocol_variances,
                &mut uses,
            );
        }
        #[cfg(test)]
        record_python_stub_batch_work(|work| {
            work.protocol_annotation_parses += 1;
        });
        let expr = PythonTypeParser::parse(&signature.ret).unwrap_or_else(|error| {
            panic!(
                "generated Python return type `{}` did not parse: {error}",
                signature.ret
            )
        });
        collect_protocol_root_uses(
            &expr,
            &root_indices,
            ProtocolPolarity::Covariant,
            false,
            protocol_variances,
            &mut uses,
        );
    }
    uses
}

#[derive(Clone, Copy, Default)]
struct ProtocolRootUse {
    covariant: bool,
    contravariant: bool,
    invariant: bool,
    invariant_protocol_argument: bool,
}

fn protocol_variance_diagnostic(uses: &[ProtocolRootUse]) -> &'static str {
    // Pyright infers variance through an invariant carrier nested in a
    // contravariant Protocol argument. Keep the carrier's exact invariance;
    // only its containing Protocol's declaration diagnostic is suppressed.
    if uses.iter().any(|uses| uses.invariant_protocol_argument) {
        "  # pyright: ignore[reportInvalidTypeVarUse]"
    } else {
        ""
    }
}

impl ProtocolRootUse {
    fn record(&mut self, polarity: ProtocolPolarity) {
        match polarity {
            ProtocolPolarity::Covariant => self.covariant = true,
            ProtocolPolarity::Contravariant => self.contravariant = true,
            ProtocolPolarity::Invariant => self.invariant = true,
        }
    }

    fn polarity(self) -> Option<ProtocolPolarity> {
        if self.invariant || self.covariant && self.contravariant {
            Some(ProtocolPolarity::Invariant)
        } else if self.covariant {
            Some(ProtocolPolarity::Covariant)
        } else if self.contravariant {
            Some(ProtocolPolarity::Contravariant)
        } else {
            None
        }
    }
}

#[cfg(all(test, feature = "surface"))]
fn protocol_root_polarity(
    root: &str,
    signatures: &[FnSig],
    protocol_variances: &BTreeMap<String, Vec<ProtocolPolarity>>,
) -> Option<ProtocolPolarity> {
    let uses = protocol_root_uses(&[root.to_owned()], signatures, protocol_variances);
    uses.into_iter()
        .next()
        .expect("one requested Python protocol root")
        .polarity()
}

fn collect_protocol_root_uses(
    expr: &PythonTypeExpr,
    root_indices: &BTreeMap<&str, usize>,
    polarity: ProtocolPolarity,
    contravariant_protocol_argument: bool,
    protocol_variances: &BTreeMap<String, Vec<ProtocolPolarity>>,
    uses: &mut [ProtocolRootUse],
) {
    #[cfg(test)]
    record_python_stub_batch_work(|work| {
        work.protocol_annotation_nodes += 1;
    });
    match expr {
        PythonTypeExpr::Name(name) => {
            if let Some(index) = root_indices.get(name.as_str()) {
                uses[*index].record(polarity);
                uses[*index].invariant_protocol_argument |=
                    contravariant_protocol_argument && polarity == ProtocolPolarity::Invariant;
            }
        }
        PythonTypeExpr::List(items) | PythonTypeExpr::Union(items) => {
            for item in items {
                collect_protocol_root_uses(
                    item,
                    root_indices,
                    polarity,
                    contravariant_protocol_argument,
                    protocol_variances,
                    uses,
                );
            }
        }
        PythonTypeExpr::Apply { head, args } if head == "__kio_typing__.Callable" => {
            if let Some(params) = args.first() {
                collect_protocol_root_uses(
                    params,
                    root_indices,
                    polarity.compose(ProtocolPolarity::Contravariant),
                    contravariant_protocol_argument,
                    protocol_variances,
                    uses,
                );
            }
            if let Some(ret) = args.get(1) {
                collect_protocol_root_uses(
                    ret,
                    root_indices,
                    polarity,
                    contravariant_protocol_argument,
                    protocol_variances,
                    uses,
                );
            }
        }
        PythonTypeExpr::Apply { head, args } => {
            if let Some(variances) = protocol_variances.get(head) {
                debug_assert_eq!(variances.len(), args.len());
                for (arg, variance) in args.iter().zip(variances) {
                    collect_protocol_root_uses(
                        arg,
                        root_indices,
                        polarity.compose(*variance),
                        contravariant_protocol_argument
                            || (*variance == ProtocolPolarity::Contravariant
                                && polarity != ProtocolPolarity::Invariant),
                        protocol_variances,
                        uses,
                    );
                }
            } else {
                for arg in args {
                    collect_protocol_root_uses(
                        arg,
                        root_indices,
                        ProtocolPolarity::Invariant,
                        contravariant_protocol_argument,
                        protocol_variances,
                        uses,
                    );
                }
            }
        }
    }
}

