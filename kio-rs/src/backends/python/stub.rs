/// A typed-stub render failure. Mirrors the Python body emitter's
/// [`super::emit::EmitError`] so the build dispatcher reports both
/// artifacts uniformly.
#[derive(Debug)]
pub struct EmitError {
    pub message: String,
}

impl std::fmt::Display for EmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for EmitError {}

/// Files beneath the generated `<ns>/` stub package.
#[derive(Debug, Eq, PartialEq)]
pub struct PythonStubPackage {
    files: BTreeMap<String, String>,
}

impl PythonStubPackage {
    pub fn files(&self) -> impl Iterator<Item = (&str, &str)> {
        self.files
            .iter()
            .map(|(path, content)| (path.as_str(), content.as_str()))
    }

    #[cfg(all(test, feature = "surface"))]
    fn file(&self, path: &str) -> Option<&str> {
        self.files.get(path).map(String::as_str)
    }
}

/// Render the package's flat typed stub: the `<Handle>Host`
/// protocol, the `create_<value-brand>` factory, and the typed `<Handle>` surface,
/// all from the compiler-prepared callable and nominal plans.
/// Package brands derive from the effective namespace `ns` through
/// `crate::backends::namespace`, shared with the `.py` factory, so the stub
/// and runtime module agree while the artifact stem remains unchanged.
pub fn lower_package_to_stub(package: &Package<Routed>, ns: &str) -> Result<String, EmitError> {
    lower_package_to_stub_with_signature(package, ns, None)
}

/// Render a stub with sealed signature history available to shared boundary
/// preparation. Python emits only live declarations; history-only sites and
/// their dependencies contribute no type, method, or package capability.
pub fn lower_package_to_stub_with_signature(
    package: &Package<Routed>,
    ns: &str,
    sig: Option<&(u32, crate::sig::ReplayedInterface)>,
) -> Result<String, EmitError> {
    let prepared =
        PreparedBoundaryCallableSites::collect(package, sig.map(|(_, replayed)| replayed))
            .map_err(|error| EmitError {
                message: format!("cannot prepare Python boundary: {error}"),
            })?;
    PreparedPythonStub::new(&prepared, pascal_case(ns), ns).render()
}

/// Render the package's `<ns>/` typed-stub package for filesystem emission.
/// The public `__init__.pyi` re-exports bounded private declaration shards.
pub fn lower_package_to_stub_package(
    package: &Package<Routed>,
    ns: &str,
) -> Result<PythonStubPackage, EmitError> {
    lower_package_to_stub_package_with_signature(package, ns, None)
}

/// Render a sharded stub package with sealed signature history available to
/// shared boundary preparation. Python still emits only live declarations.
pub fn lower_package_to_stub_package_with_signature(
    package: &Package<Routed>,
    ns: &str,
    sig: Option<&(u32, crate::sig::ReplayedInterface)>,
) -> Result<PythonStubPackage, EmitError> {
    shard_python_stub(lower_package_to_stub_with_signature(package, ns, sig)?)
}

#[derive(Clone, Default)]
struct PythonFacadeScope {
    binders: BTreeMap<FacadeBinderId, String>,
}

impl PythonFacadeScope {
    fn bind(&mut self, id: FacadeBinderId, rendered: String) {
        self.binders.insert(id, rendered);
    }

    fn lookup(&self, id: FacadeBinderId) -> Result<&str, EmitError> {
        self.binders
            .get(&id)
            .map(String::as_str)
            .ok_or_else(|| prepared_error("facade refers to an unbound type variable"))
    }
}

#[derive(Default)]
struct PreparedSurfaceTree {
    entries: BTreeMap<String, PreparedSurfaceNode>,
}

enum PreparedSurfaceNode {
    Interior(PreparedSurfaceTree),
    Fn(FnSig),
}

impl PreparedSurfaceTree {
    fn insert(&mut self, path: &[String], node: PreparedSurfaceNode) {
        debug_assert!(!path.is_empty());
        if path.len() == 1 {
            assert!(self.entries.insert(path[0].clone(), node).is_none());
            return;
        }
        let entry = self
            .entries
            .entry(path[0].clone())
            .or_insert_with(|| PreparedSurfaceNode::Interior(Self::default()));
        let PreparedSurfaceNode::Interior(children) = entry else {
            unreachable!("prepared Python facade path crosses a value leaf")
        };
        children.insert(&path[1..], node);
    }
}

