fn exact_qtn_frame(name: &QualifiedTypeName) -> String {
    let mut out = format!("M{}_", name.module_segments().len());
    for segment in name.module_segments() {
        let segment = host_name_core(segment);
        out.push_str(&format!("C{}_{segment}", segment.len()));
    }
    let leaf = host_name_core(name.name());
    out.push_str(&format!("N{}_{leaf}", leaf.len()));
    out
}

fn exact_site_frame(site: PreparedBoundaryCallableSite<'_>) -> String {
    let mut out = format!("M{}_", site.site().module_segments().len());
    for segment in site.site().module_segments() {
        let segment = host_name_core(segment);
        out.push_str(&format!("C{}_{segment}", segment.len()));
    }
    let (role, components) = match site.site().owner() {
        BoundaryFacadeSiteOwner::HostFunction { name } => ("Host", vec![name.as_str()]),
        BoundaryFacadeSiteOwner::ExportedFunction { name } => ("Export", vec![name.as_str()]),
        BoundaryFacadeSiteOwner::NewtypeConstructor { newtype, member } => {
            ("Ctor", vec![newtype.as_str(), member.as_str()])
        }
        BoundaryFacadeSiteOwner::NewtypeProjector { newtype, member } => {
            ("Proj", vec![newtype.as_str(), member.as_str()])
        }
    };
    out.push_str(&format!("R{}_{role}", role.len()));
    for component in components {
        let component = host_name_core(component);
        out.push_str(&format!("N{}_{component}", component.len()));
    }
    out
}

fn readable_site_alias(site: PreparedBoundaryCallableSite<'_>) -> String {
    let module = site.site().module_segments().join("/");
    let (role, names) = match site.site().owner() {
        BoundaryFacadeSiteOwner::HostFunction { name } => ("Host", vec![name]),
        BoundaryFacadeSiteOwner::ExportedFunction { name } => ("Export", vec![name]),
        BoundaryFacadeSiteOwner::NewtypeConstructor { newtype, member } => {
            ("Ctor", vec![newtype, member])
        }
        BoundaryFacadeSiteOwner::NewtypeProjector { newtype, member } => {
            ("Proj", vec![newtype, member])
        }
    };
    format!(
        "KioView{role}_{}",
        crate::backends::public_names::readable_public_identity(
            std::iter::once(module.as_str()).chain(names.into_iter().map(String::as_str)),
        )
    )
}

