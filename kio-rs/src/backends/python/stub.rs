struct PreparedPythonStub<'a> {
    prepared: &'a PreparedBoundaryCallableSites,
    handle: String,
    namespace: String,
    root_bindings: BTreeMap<QualifiedTypeName, String>,
    live_newtype_representatives: LiveNewtypeRepresentatives<'a>,
    typevars: BTreeMap<String, String>,
    declaration_defs: BTreeMap<String, String>,
    shape_defs: BTreeMap<String, String>,
    typed_dict_representatives: BTreeMap<PythonTypedDictDefinition, String>,
    protocol_defs: BTreeMap<String, String>,
    protocol_variances: BTreeMap<String, Vec<ProtocolPolarity>>,
    payload_alias_defs: BTreeMap<String, String>,
    transparent_expansion_stack: Vec<QualifiedTypeName>,
    recursive_payloads: BTreeSet<QualifiedTypeName>,
    hkt_defs: BTreeMap<String, String>,
}

impl<'a> PreparedPythonStub<'a> {
    fn new(prepared: &'a PreparedBoundaryCallableSites, handle: String, namespace: &str) -> Self {
        // Python 3.10's stdlib-only type-stub surface has no recognized
        // deprecation marker. Per `specs/backends/python.md` § History-only
        // generated names are not source-stable on Python, omit retained
        // roots instead of publishing them unmarked or forcing a current host
        // to select removed types.
        let root_bindings = prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
            .filter(|binding| binding.type_params().is_empty())
            .map(|binding| {
                let name = format!("KioHost_{}", exact_qtn_frame(binding.name()));
                (binding.name().clone(), name)
            })
            .collect();
        // Index each exact live nominal owner once. Public-newtype rendering
        // then performs one logarithmic lookup per declaration instead of
        // rescanning every callable site for every carrier.
        let live_newtype_representatives = LiveNewtypeRepresentatives::new(prepared);
        Self {
            prepared,
            handle,
            namespace: namespace.to_owned(),
            root_bindings,
            live_newtype_representatives,
            typevars: BTreeMap::new(),
            declaration_defs: BTreeMap::new(),
            shape_defs: BTreeMap::new(),
            typed_dict_representatives: BTreeMap::new(),
            protocol_defs: BTreeMap::new(),
            protocol_variances: BTreeMap::new(),
            payload_alias_defs: BTreeMap::new(),
            transparent_expansion_stack: Vec::new(),
            recursive_payloads: BTreeSet::new(),
            hkt_defs: BTreeMap::new(),
        }
    }

    fn render(mut self) -> Result<String, EmitError> {
        for binding in self.root_bindings.values().cloned().collect::<Vec<_>>() {
            self.declare_typevar(&binding);
        }
        self.render_host_type_declarations();
        self.render_public_newtype_declarations()?;
        let host = self.render_prepared_host()?;
        let handle = self.render_prepared_handle()?;
        let factory = self.render_factory();

        let mut out = String::from(PYTHON_STUB_HEADER);
        for declaration in self.typevars.values() {
            out.push_str(declaration);
            out.push('\n');
        }
        if !self.typevars.is_empty() {
            out.push('\n');
        }
        for definition in self.hkt_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.declaration_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.shape_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.protocol_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        for definition in self.payload_alias_defs.values() {
            out.push_str(definition);
            out.push('\n');
        }
        out.push_str(&host);
        out.push('\n');
        out.push_str(&handle);
        out.push_str(&factory);
        Ok(out)
    }

    fn declare_typevar(&mut self, name: &str) {
        self.typevars
            .entry(name.to_owned())
            .or_insert_with(|| format!("{name} = typing.TypeVar({})", py_string_literal(name)));
    }

    fn declare_protocol_typevar(&mut self, name: &str, polarity: ProtocolPolarity) {
        self.typevars.entry(name.to_owned()).or_insert_with(|| {
            let variance = match polarity {
                ProtocolPolarity::Covariant => ", covariant=True",
                ProtocolPolarity::Contravariant => ", contravariant=True",
                ProtocolPolarity::Invariant => "",
            };
            format!(
                "{name} = typing.TypeVar({}{variance})",
                py_string_literal(name)
            )
        });
    }

    fn localize_protocol_typevars(
        &mut self,
        context: &str,
        protocol: &str,
        typevars: Vec<String>,
        include_phantom_typevars: bool,
        signatures: &mut [FnSig],
    ) -> (Vec<String>, Vec<String>) {
        let mut seen = BTreeSet::new();
        let requested = typevars
            .into_iter()
            .filter(|typevar| seen.insert(typevar.clone()))
            .collect::<Vec<_>>();
        let uses = protocol_root_uses(&requested, signatures, &self.protocol_variances);
        let mut locals = Vec::new();
        let mut arguments = Vec::new();
        let mut variances = Vec::new();
        let mut replacements = BTreeMap::new();
        for (index, (typevar, use_sites)) in requested.into_iter().zip(uses).enumerate() {
            let polarity = match use_sites.polarity() {
                Some(polarity) => polarity,
                // A phantom protocol parameter is safe in either direction;
                // choose covariance so Python type checkers accept the
                // declaration while the outer host still preserves every
                // exact root argument.
                None if include_phantom_typevars => ProtocolPolarity::Covariant,
                None => continue,
            };
            let local = format!("KioProtocol_{context}_B{index}");
            self.declare_protocol_typevar(&local, polarity);
            replacements.insert(typevar.clone(), local.clone());
            locals.push(local);
            arguments.push(typevar);
            variances.push(polarity);
        }
        if !replacements.is_empty() {
            for signature in signatures.iter_mut() {
                for param in &mut signature.params {
                    *param = replace_python_identifiers(param, &replacements);
                }
                signature.ret = replace_python_identifiers(&signature.ret, &replacements);
            }
        }
        if let Some(previous) = self
            .protocol_variances
            .insert(protocol.to_owned(), variances.clone())
        {
            debug_assert_eq!(previous, variances);
        }
        (locals, arguments)
    }

    fn root_typevars(&self) -> Vec<String> {
        self.root_bindings.values().cloned().collect()
    }

    fn generic_class_bases(&self, primary: &str, extra: &[String]) -> String {
        let mut args = self.root_typevars();
        args.extend(extra.iter().cloned());
        if args.is_empty() {
            primary.to_owned()
        } else {
            format!("{primary}, typing.Generic[{}]", args.join(", "))
        }
    }

    fn render_host_type_declarations(&mut self) {
        // Keep the stub live-only per `specs/backends/python.md` §
        // History-only generated names are not source-stable on Python.
        for binding in self
            .prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
        {
            if binding.type_params().is_empty() {
                continue;
            }
            let frame = exact_qtn_frame(binding.name());
            let class_name = format!("KioHostType_{frame}");
            let params = binding
                .type_params()
                .iter()
                .enumerate()
                .map(|(index, _)| format!("KioHostParam_{frame}_{index}"))
                .collect::<Vec<_>>();
            for param in &params {
                self.declare_typevar(param);
            }
            let applied = format!("{class_name}[{}]", params.join(", "));
            let definition = format!(
                "class {class_name}(typing.Generic[{}]):\n    @classmethod\n    def from_native(cls, value: object, /) -> {applied}: ...\n    def to_native(self, /) -> object: ...\n",
                params.join(", ")
            );
            self.declaration_defs.insert(class_name, definition);
        }
    }

    fn render_public_newtype_declarations(&mut self) -> Result<(), EmitError> {
        // `public_newtypes` is the live inventory; the retained inventory is
        // deliberately absent under the Python history-omission contract in
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        let inventory = self.prepared.public_newtypes().cloned().collect::<Vec<_>>();
        for entry in inventory {
            let frame = exact_qtn_frame(entry.name());
            let class_name = format!("KioNewtype_{frame}");
            let params = entry
                .type_params()
                .iter()
                .enumerate()
                .map(|(index, _)| format!("KioNewtypeParam_{frame}_{index}"))
                .collect::<Vec<_>>();
            for param in &params {
                self.declare_typevar(param);
            }
            let representative = self
                .live_newtype_representatives
                .get(entry.name())
                .and_then(|site| {
                    site.nominals()
                        .declaration(entry.name())
                        .map(|declaration| (site, declaration))
                });
            let transparent = representative.and_then(|(site, declaration)| match declaration {
                BoundaryNominalDeclaration::Newtype {
                    existential_params,
                    transparent_payload: Some(payload),
                    surface,
                    ..
                } if existential_params.is_empty() && !surface.uses_nominal_carrier() => {
                    Some((site, payload))
                }
                _ => None,
            });
            let definition = if let Some((site, payload)) = transparent {
                let execution_layout = site.execution().ok_or_else(|| {
                    prepared_error("public newtype payload has no live execution layout")
                })?;
                let payload_execution = execution_layout
                    .transparent_payload(entry.name())
                    .ok_or_else(|| {
                        prepared_error("public newtype payload has no prepared execution plan")
                    })?;
                let mut scope = PythonFacadeScope::default();
                if payload.declaration_binders().len() != params.len() {
                    return Err(prepared_error(
                        "public newtype binder arity disagrees with its prepared payload",
                    ));
                }
                for (binder, rendered) in payload.declaration_binders().iter().zip(&params) {
                    scope.bind(*binder, rendered.clone());
                }
                self.transparent_expansion_stack.push(entry.name().clone());
                let payload_ty = self.render_facade_use(
                    site,
                    payload.facade(),
                    payload.payload_root(),
                    payload_execution,
                    execution_layout,
                    site.nominals(),
                    &scope,
                    &format!("Newtype_{frame}"),
                    false,
                );
                let popped = self
                    .transparent_expansion_stack
                    .pop()
                    .expect("the public Python newtype expansion was pushed");
                debug_assert_eq!(popped, *entry.name());
                let payload_ty = payload_ty?;
                let payload_ty = if self.recursive_payloads.contains(entry.name()) {
                    let alias = format!("KioPayload_{frame}");
                    self.payload_alias_defs.insert(
                        alias.clone(),
                        format!("{alias}: typing.TypeAlias = {payload_ty}\n"),
                    );
                    let mut all = self.root_typevars();
                    all.extend(params.iter().cloned());
                    apply_py_type(&alias, &all)
                } else {
                    payload_ty
                };
                let bases = self.generic_class_bases("typing.TypedDict", &params);
                format!(
                    "class {class_name}({bases}):\n    {}: {payload_ty}\n",
                    host_name_core(entry.name().name())
                )
            } else {
                let bases = self.generic_class_bases("typing.Generic", &params);
                if bases == "typing.Generic" {
                    format!("class {class_name}:\n    ...\n")
                } else {
                    // `generic_class_bases` treats its primary as an ordinary
                    // base; nominal carriers need only the Generic base.
                    let mut all = self.root_typevars();
                    all.extend(params.iter().cloned());
                    format!(
                        "class {class_name}(typing.Generic[{}]):\n    ...\n",
                        all.join(", ")
                    )
                }
            };
            self.declaration_defs.insert(class_name, definition);
        }
        Ok(())
    }

    fn render_prepared_host(&mut self) -> Result<String, EmitError> {
        let host_name = format!("{}Host", self.handle);
        let mut by_namespace: BTreeMap<String, Vec<PreparedBoundaryCallableSite<'_>>> =
            BTreeMap::new();
        // Execution provenance is the live-only callable gate required by
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        for site in self.prepared.sites() {
            if site.execution().is_some()
                && matches!(
                    site.site().owner(),
                    BoundaryFacadeSiteOwner::HostFunction { .. }
                )
            {
                by_namespace
                    .entry(host_module_key(&site.site().module_segments().join("/")))
                    .or_default()
                    .push(site);
            }
        }
        let mut nested = String::new();
        let mut properties = Vec::new();
        for (namespace, sites) in by_namespace {
            let nested_name = format!("_{host_name}_{namespace}");
            let mut methods = Vec::new();
            let mut needs_getattr = false;
            for site in sites {
                let BoundaryFacadeSiteOwner::HostFunction { name } = site.site().owner() else {
                    unreachable!()
                };
                let name = host_name_core(name);
                if is_spellable(&name) {
                    methods.push((name, self.render_prepared_callable(site)?));
                } else {
                    needs_getattr = true;
                }
            }
            let mut signatures = methods
                .iter()
                .map(|(_, signature)| signature.clone())
                .collect::<Vec<_>>();
            let (locals, arguments) = self.localize_protocol_typevars(
                &format!("Host_{namespace}"),
                &nested_name,
                self.root_typevars(),
                false,
                &mut signatures,
            );
            let bases = if locals.is_empty() {
                "typing.Protocol".to_owned()
            } else {
                format!("typing.Protocol[{}]", locals.join(", "))
            };
            nested.push_str(&format!("class {nested_name}({bases}):\n"));
            for ((name, _), signature) in methods.iter().zip(&signatures) {
                nested.push_str(&format!(
                    "    def {name}(self{}) -> {}: ...{}\n",
                    positional_method_params(&signature.params),
                    signature.ret,
                    signature.pyright_suppression()
                ));
            }
            if needs_getattr {
                nested.push_str("    def __getattr__(self, name: str) -> object: ...\n");
            } else if signatures.is_empty() {
                nested.push_str("    ...\n");
            }
            nested.push('\n');
            properties.push((namespace, apply_py_type(&nested_name, &arguments)));
        }

        let mut members = Vec::new();
        // Retained bindings cannot become protocol obligations; see
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        let bindings = self
            .prepared
            .host_bindings()
            .filter(|binding| matches!(binding.origin(), BoundaryHostBindingOrigin::Live))
            .cloned()
            .collect::<Vec<_>>();
        for binding in bindings {
            let BoundaryHostTypeBinding::Role(role) = binding.binding() else {
                continue;
            };
            if !binding.type_params().is_empty() {
                return Err(prepared_error(
                    "role-bearing Python host type has positive constructor arity",
                ));
            }
            let exact = self.root_bindings.get(binding.name()).ok_or_else(|| {
                prepared_error("role-bearing host type has no exact root binding")
            })?;
            let primitive = role_to_py_type(role);
            let frame = readable_role_adapter_identity(
                binding.name().module_segments(),
                binding.name().name(),
            )
            .unwrap_or_else(|| exact_qtn_frame(binding.name()));
            members.push((
                HostProtocolMember::Adapter(format!("KioHostIn_{frame}")),
                FnSig {
                    params: vec![exact.clone()],
                    ret: primitive.to_owned(),
                    suppress_invalid_typevar_use: false,
                },
            ));
            members.push((
                HostProtocolMember::Adapter(format!("KioHostOut_{frame}")),
                FnSig {
                    params: vec![primitive.to_owned()],
                    ret: exact.clone(),
                    suppress_invalid_typevar_use: false,
                },
            ));
        }
        for (name, ret) in properties {
            members.push((
                HostProtocolMember::Property(name),
                FnSig {
                    params: Vec::new(),
                    ret,
                    suppress_invalid_typevar_use: false,
                },
            ));
        }
        let mut signatures = members
            .iter()
            .map(|(_, signature)| signature.clone())
            .collect::<Vec<_>>();
        let (locals, arguments) = self.localize_protocol_typevars(
            "HostRoot",
            &host_name,
            self.root_typevars(),
            true,
            &mut signatures,
        );
        debug_assert_eq!(arguments, self.root_typevars());
        let bases = if locals.is_empty() {
            "typing.Protocol".to_owned()
        } else {
            format!("typing.Protocol[{}]", locals.join(", "))
        };
        let mut outer = format!("class {host_name}({bases}):\n");
        for ((member, _), signature) in members.iter().zip(&signatures) {
            match member {
                HostProtocolMember::Adapter(name) => {
                    let [param] = signature.params.as_slice() else {
                        unreachable!("a Python role adapter has exactly one parameter")
                    };
                    outer.push_str(&format!(
                        "    def {name}(self, value: {param}, /) -> {}: ...\n",
                        signature.ret
                    ));
                }
                HostProtocolMember::Property(name) => outer.push_str(&format!(
                    "    @property\n    def {name}(self) -> {}: ...\n",
                    signature.ret
                )),
            }
        }
        if members.is_empty() {
            outer.push_str("    ...\n");
        }
        Ok(format!("{nested}{outer}"))
    }

    fn render_prepared_handle(&mut self) -> Result<String, EmitError> {
        let mut tree = PreparedSurfaceTree::default();
        for entry in self.prepared.public_newtypes() {
            let mut path = python_facade_module_path(entry.name().module_segments());
            path.push(FacadeSelector::Type(entry.name().name().to_owned()).facade_name(false));
            tree.insert(
                &path,
                PreparedSurfaceNode::Interior(PreparedSurfaceTree::default()),
            );
        }
        // Only executable (live) sites enter the current handle; see
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        for site in self
            .prepared
            .sites()
            .filter(|site| site.execution().is_some())
        {
            let mut path = python_facade_module_path(site.site().module_segments());
            match site.site().owner() {
                BoundaryFacadeSiteOwner::HostFunction { .. } => continue,
                BoundaryFacadeSiteOwner::ExportedFunction { name } => {
                    path.push(host_name_core(name))
                }
                BoundaryFacadeSiteOwner::NewtypeConstructor { newtype, member }
                | BoundaryFacadeSiteOwner::NewtypeProjector { newtype, member } => {
                    path.push(FacadeSelector::Type(newtype.clone()).facade_name(false));
                    path.push(host_name_core(member));
                }
            }
            tree.insert(
                &path,
                PreparedSurfaceNode::Fn(self.render_prepared_callable(site)?),
            );
        }
        let mut out = String::new();
        self.render_prepared_tree(&tree, &self.handle.clone(), &[], &mut out);
        Ok(out)
    }

    fn render_prepared_tree(
        &self,
        tree: &PreparedSurfaceTree,
        class_name: &str,
        path: &[String],
        out: &mut String,
    ) {
        let roots = self.root_typevars();
        let mut members = Vec::new();
        let mut needs_getattr = false;
        for (segment, child) in &tree.entries {
            match child {
                PreparedSurfaceNode::Interior(children) => {
                    let mut child_path = path.to_vec();
                    child_path.push(segment.clone());
                    let child_name = format!(
                        "_{}_{}",
                        self.handle,
                        child_path
                            .iter()
                            .map(|part| encode_python_source(part))
                            .collect::<Vec<_>>()
                            .join("_")
                    );
                    self.render_prepared_tree(children, &child_name, &child_path, out);
                    if is_spellable(segment) {
                        members.push(format!(
                            "    {segment}: {}",
                            apply_py_type(&child_name, &roots)
                        ));
                    } else {
                        needs_getattr = true;
                    }
                }
                PreparedSurfaceNode::Fn(sig) => {
                    if is_spellable(segment) {
                        members.push(format!(
                            "    def {segment}(self{}) -> {}: ...{}",
                            positional_method_params(&sig.params),
                            sig.ret,
                            sig.pyright_suppression()
                        ));
                    } else {
                        needs_getattr = true;
                    }
                }
            }
        }
        let bases = if roots.is_empty() {
            String::new()
        } else {
            format!("(typing.Generic[{}])", roots.join(", "))
        };
        out.push_str(&format!("class {class_name}{bases}:\n"));
        if members.is_empty() && !needs_getattr {
            out.push_str("    ...\n");
        } else {
            for member in members {
                out.push_str(&member);
                out.push('\n');
            }
            if needs_getattr {
                out.push_str("    def __getattr__(self, name: str) -> object: ...\n");
            }
        }
        out.push('\n');
    }

    fn render_factory(&self) -> String {
        let roots = self.root_typevars();
        let host_name = apply_py_type(&format!("{}Host", self.handle), &roots);
        let handle = apply_py_type(&self.handle, &roots);
        // Current-host construction depends only on live execution sites and
        // live role bindings; see the Python history-omission contract in
        // `specs/backends/python.md` § History-only generated names are not
        // source-stable on Python.
        let host_required = self.prepared.sites().any(|site| {
            site.execution().is_some()
                && matches!(
                    site.site().owner(),
                    BoundaryFacadeSiteOwner::HostFunction { .. }
                )
        }) || self.prepared.host_bindings().any(|binding| {
            matches!(binding.binding(), BoundaryHostTypeBinding::Role(_))
                && matches!(binding.origin(), BoundaryHostBindingOrigin::Live)
                && binding.type_params().is_empty()
        });
        if host_required {
            format!(
                "def create_{}(host: {host_name}) -> {handle}: ...\n",
                crate::backends::namespace::value_brand(&self.namespace)
            )
        } else {
            format!(
                "def create_{}(host: {host_name} | None = None) -> {handle}: ...\n",
                crate::backends::namespace::value_brand(&self.namespace)
            )
        }
    }

    fn render_prepared_callable(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
    ) -> Result<FnSig, EmitError> {
        let execution_layout = site
            .execution()
            .ok_or_else(|| prepared_error("Python callable has no live execution layout"))?;
        let entry = site.plan().entry();
        let context = exact_site_frame(site);
        let mut scope = PythonFacadeScope::default();
        let mut params = Vec::new();
        let mut method_typevars = Vec::new();
        for (stage_index, (semantic, execution)) in entry
            .head_stages
            .iter()
            .zip(execution_layout.head_stages())
            .enumerate()
        {
            match (semantic, execution) {
                (
                    BoundaryCallableHeadStage::Type { id, .. },
                    CallableExecutionStage::Type { .. },
                ) => {
                    let name = format!("KioType_{context}_B{}", id.index());
                    self.declare_typevar(&name);
                    scope.bind(*id, name.clone());
                    method_typevars.push(name);
                }
                (
                    BoundaryCallableHeadStage::Value { slots },
                    CallableExecutionStage::Value(layout),
                ) => params.extend(self.render_callable_params(
                    site,
                    site.plan().facade(),
                    slots,
                    layout,
                    execution_layout.root_uses(),
                    execution_layout,
                    site.nominals(),
                    &scope,
                    &format!("{context}_H{stage_index}"),
                )?),
                _ => {
                    return Err(prepared_error(
                        "Python callable head disagrees with its execution layout",
                    ));
                }
            }
        }
        let ret = self.render_facade_use(
            site,
            site.plan().facade(),
            entry.returned,
            execution_layout.root_uses(),
            execution_layout,
            site.nominals(),
            &scope,
            &context,
            false,
        )?;
        let suppress_invalid_typevar_use = method_typevars.iter().any(|typevar| {
            params
                .iter()
                .chain(std::iter::once(&ret))
                .map(|annotation| python_identifier_occurrences(annotation, typevar))
                .sum::<usize>()
                == 1
        });
        Ok(FnSig {
            params,
            ret,
            suppress_invalid_typevar_use,
        })
    }

    #[allow(clippy::too_many_arguments)]
    fn render_callable_params(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
        plan: &BoundaryFacadePlan,
        slots: &[FacadeUseId],
        layout: &CallableValueStageLayout,
        execution: &BoundaryFacadeExecutionPlan,
        execution_layout: &CallableExecutionLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
    ) -> Result<Vec<String>, EmitError> {
        let mut params = Vec::new();
        for (source_index, source) in layout.source_params().iter().enumerate() {
            let range = source.facade_slots();
            if range.end > slots.len() {
                return Err(prepared_error("Python source range exceeds facade slots"));
            }
            match source.adapter() {
                CallableSourceParamAdapter::UnitValue => {}
                CallableSourceParamAdapter::Identity => {
                    let [use_id] = &slots[range] else {
                        return Err(prepared_error(
                            "Python identity source does not own one facade slot",
                        ));
                    };
                    params.push(self.render_facade_use(
                        site,
                        plan,
                        *use_id,
                        execution,
                        execution_layout,
                        nominals,
                        scope,
                        context,
                        false,
                    )?);
                }
                CallableSourceParamAdapter::RightNest => {
                    let shell = source.product_shell().ok_or_else(|| {
                        prepared_error("Python right-nest source has no prepared shell")
                    })?;
                    let uses = &slots[range];
                    let fields = shell
                        .ordered_keys()
                        .iter()
                        .zip(uses)
                        .map(|(key, use_id)| {
                            Ok((
                                render_semantic_key(key),
                                self.render_facade_use(
                                    site,
                                    plan,
                                    *use_id,
                                    execution,
                                    execution_layout,
                                    nominals,
                                    scope,
                                    context,
                                    true,
                                )?,
                            ))
                        })
                        .collect::<Result<Vec<_>, EmitError>>()?;
                    params.push(self.synth_typed_dict(
                        &format!("KioShape_{context}_P{source_index}"),
                        &fields,
                        scope,
                    ));
                }
            }
        }
        Ok(params)
    }

    #[allow(clippy::too_many_arguments)]
    fn render_facade_use(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
        plan: &BoundaryFacadePlan,
        use_id: FacadeUseId,
        execution: &BoundaryFacadeExecutionPlan,
        execution_layout: &CallableExecutionLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
        absorb_transparent: bool,
    ) -> Result<String, EmitError> {
        match plan.use_at(use_id) {
            FacadeUse::Unit { .. } => Ok("None".to_owned()),
            FacadeUse::Bottom { .. } => Ok("typing.NoReturn".to_owned()),
            FacadeUse::Bound { binder, .. } => Ok(scope.lookup(*binder)?.to_owned()),
            FacadeUse::Nominal { name, .. } => self.render_facade_nominal(
                site,
                plan,
                name,
                &[],
                execution,
                execution_layout,
                nominals,
                scope,
                context,
                absorb_transparent,
            ),
            FacadeUse::Apply {
                constructor, args, ..
            } => {
                if let FacadeUse::Nominal { name, .. } = plan.use_at(*constructor) {
                    return self.render_facade_nominal(
                        site,
                        plan,
                        name,
                        args,
                        execution,
                        execution_layout,
                        nominals,
                        scope,
                        context,
                        absorb_transparent,
                    );
                }
                let head = self.render_facade_use(
                    site,
                    plan,
                    *constructor,
                    execution,
                    execution_layout,
                    nominals,
                    scope,
                    context,
                    false,
                )?;
                let args = self.render_facade_args(
                    site,
                    plan,
                    args,
                    execution,
                    execution_layout,
                    nominals,
                    scope,
                    context,
                )?;
                Ok(self.render_hkt_application(&head, &args))
            }
            FacadeUse::Product { shell, args, .. } => {
                let fields = shell
                    .ordered_keys()
                    .iter()
                    .zip(args)
                    .map(|(key, child)| {
                        Ok((
                            render_semantic_key(key),
                            self.render_facade_use(
                                site,
                                plan,
                                *child,
                                execution,
                                execution_layout,
                                nominals,
                                scope,
                                context,
                                true,
                            )?,
                        ))
                    })
                    .collect::<Result<Vec<_>, EmitError>>()?;
                Ok(self.synth_typed_dict(
                    &format!("KioShape_{context}_U{}", use_id.index()),
                    &fields,
                    scope,
                ))
            }
            FacadeUse::Sum { shell, args, .. } => {
                let mut arms = Vec::new();
                for (index, (key, child)) in shell.ordered_keys().iter().zip(args).enumerate() {
                    let value = self.render_facade_use(
                        site,
                        plan,
                        *child,
                        execution,
                        execution_layout,
                        nominals,
                        scope,
                        context,
                        true,
                    )?;
                    arms.push(self.synth_typed_dict(
                        &format!("KioShape_{context}_U{}_A{index}", use_id.index()),
                        &[(render_semantic_key(key), value)],
                        scope,
                    ));
                }
                Ok(arms.join(" | "))
            }
            FacadeUse::Function { slots, result, .. } => {
                let BoundaryFacadeExecutionUse::Function(layout) = execution.use_at(use_id) else {
                    return Err(prepared_error(
                        "Python function facade has no prepared execution layout",
                    ));
                };
                let params = self.render_callable_params(
                    site,
                    plan,
                    slots,
                    layout,
                    execution,
                    execution_layout,
                    nominals,
                    scope,
                    &format!("{context}_U{}", use_id.index()),
                )?;
                let ret = self.render_facade_use(
                    site,
                    plan,
                    *result,
                    execution,
                    execution_layout,
                    nominals,
                    scope,
                    context,
                    false,
                )?;
                Ok(format!("typing.Callable[[{}], {ret}]", params.join(", ")))
            }
            FacadeUse::Forall { .. } => self.render_forall_protocol(
                site,
                plan,
                use_id,
                execution,
                execution_layout,
                nominals,
                scope,
                context,
            ),
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn render_facade_args(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
        plan: &BoundaryFacadePlan,
        args: &[FacadeUseId],
        execution: &BoundaryFacadeExecutionPlan,
        execution_layout: &CallableExecutionLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
    ) -> Result<Vec<String>, EmitError> {
        args.iter()
            .map(|arg| {
                self.render_facade_use(
                    site,
                    plan,
                    *arg,
                    execution,
                    execution_layout,
                    nominals,
                    scope,
                    context,
                    false,
                )
            })
            .collect()
    }

    #[allow(clippy::too_many_arguments)]
    fn render_facade_nominal(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
        plan: &BoundaryFacadePlan,
        name: &QualifiedTypeName,
        args: &[FacadeUseId],
        execution: &BoundaryFacadeExecutionPlan,
        execution_layout: &CallableExecutionLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
        absorb_transparent: bool,
    ) -> Result<String, EmitError> {
        let declaration = nominals
            .declaration(name)
            .ok_or_else(|| prepared_error("Python facade omitted an exact nominal dependency"))?;
        let rendered_args = self.render_facade_args(
            site,
            plan,
            args,
            execution,
            execution_layout,
            nominals,
            scope,
            context,
        )?;
        match declaration {
            BoundaryNominalDeclaration::HostType { type_params, .. } => {
                if rendered_args.len() > type_params.len() {
                    return Err(prepared_error(
                        "Python host-type application exceeds declaration arity",
                    ));
                }
                if type_params.is_empty() {
                    return self
                        .root_bindings
                        .get(name)
                        .cloned()
                        .ok_or_else(|| prepared_error("exact Python host binding is absent"));
                }
                let frame = exact_qtn_frame(name);
                if rendered_args.len() == type_params.len() {
                    return Ok(format!("KioHostType_{frame}[{}]", rendered_args.join(", ")));
                }
                let witness = self.ensure_constructor_witness("Host", name, type_params.len());
                if rendered_args.is_empty() {
                    Ok(witness)
                } else {
                    Ok(self.render_hkt_application(&witness, &rendered_args))
                }
            }
            BoundaryNominalDeclaration::Newtype {
                type_params,
                existential_params,
                transparent_payload,
                surface,
            } => {
                if rendered_args.len() > type_params.len() {
                    return Err(prepared_error(
                        "Python newtype application exceeds declaration arity",
                    ));
                }
                if rendered_args.len() < type_params.len() {
                    let witness =
                        self.ensure_constructor_witness("Newtype", name, type_params.len());
                    return if rendered_args.is_empty() {
                        Ok(witness)
                    } else {
                        Ok(self.render_hkt_application(&witness, &rendered_args))
                    };
                }
                if absorb_transparent
                    && existential_params.is_empty()
                    && !surface.uses_nominal_carrier()
                    && let Some(payload) = transparent_payload
                {
                    if self.transparent_expansion_stack.contains(name) {
                        self.recursive_payloads.insert(name.clone());
                        let mut all = self.root_typevars();
                        all.extend(rendered_args);
                        return Ok(apply_py_type(
                            &format!("KioPayload_{}", exact_qtn_frame(name)),
                            &all,
                        ));
                    }
                    let payload_execution =
                        execution_layout.transparent_payload(name).ok_or_else(|| {
                            prepared_error("transparent Python nominal has no execution plan")
                        })?;
                    if payload.declaration_binders().len() != rendered_args.len() {
                        return Err(prepared_error(
                            "transparent Python nominal has inconsistent binder arity",
                        ));
                    }
                    let mut nested = scope.clone();
                    for (binder, rendered) in
                        payload.declaration_binders().iter().zip(&rendered_args)
                    {
                        nested.bind(*binder, rendered.clone());
                    }
                    self.transparent_expansion_stack.push(name.clone());
                    let rendered = self.render_facade_use(
                        site,
                        payload.facade(),
                        payload.payload_root(),
                        payload_execution,
                        execution_layout,
                        nominals,
                        &nested,
                        &format!("{context}_N{}", exact_qtn_frame(name)),
                        false,
                    );
                    let popped = self
                        .transparent_expansion_stack
                        .pop()
                        .expect("the nested Python newtype expansion was pushed");
                    debug_assert_eq!(popped, *name);
                    return rendered;
                }
                let mut all = self.root_typevars();
                all.extend(rendered_args);
                Ok(apply_py_type(
                    &format!("KioNewtype_{}", exact_qtn_frame(name)),
                    &all,
                ))
            }
        }
    }

    fn ensure_constructor_witness(
        &mut self,
        category: &str,
        name: &QualifiedTypeName,
        arity: usize,
    ) -> String {
        let witness = format!("Kio{category}Mk_{}", exact_qtn_frame(name));
        let roots = if category == "Newtype" {
            self.root_typevars()
        } else {
            Vec::new()
        };
        self.hkt_defs.entry(witness.clone()).or_insert_with(|| {
            let bases = if roots.is_empty() {
                String::new()
            } else {
                format!("(typing.Generic[{}])", roots.join(", "))
            };
            format!(
                "class {witness}{bases}:\n    # Declaration-owned witness for an unsaturated arity-{arity} constructor.\n    ...\n"
            )
        });
        apply_py_type(&witness, &roots)
    }

    fn render_hkt_application(&mut self, head: &str, args: &[String]) -> String {
        if args.is_empty() {
            return head.to_owned();
        }
        let name = format!("KioApply{}", args.len());
        if !self.hkt_defs.contains_key(&name) {
            let head_var = format!("{name}_Constructor");
            self.declare_typevar(&head_var);
            let arg_vars = (0..args.len())
                .map(|index| format!("{name}_Arg{index}"))
                .collect::<Vec<_>>();
            for arg in &arg_vars {
                self.declare_typevar(arg);
            }
            let mut params = vec![head_var];
            params.extend(arg_vars);
            self.hkt_defs.insert(
                name.clone(),
                format!(
                    "class {name}(typing.Generic[{}]):\n    ...\n",
                    params.join(", ")
                ),
            );
        }
        let mut applied = vec![head.to_owned()];
        applied.extend(args.iter().cloned());
        format!("{name}[{}]", applied.join(", "))
    }

    #[allow(clippy::too_many_arguments)]
    fn render_forall_protocol(
        &mut self,
        site: PreparedBoundaryCallableSite<'_>,
        plan: &BoundaryFacadePlan,
        root: FacadeUseId,
        execution: &BoundaryFacadeExecutionPlan,
        execution_layout: &CallableExecutionLayout,
        nominals: &BoundaryNominalDependencies,
        scope: &PythonFacadeScope,
        context: &str,
    ) -> Result<String, EmitError> {
        let mut nested = scope.clone();
        let mut current = root;
        while let FacadeUse::Forall { binder, result, .. } = plan.use_at(current) {
            let name = format!("KioType_{context}_B{}", binder.index());
            self.declare_typevar(&name);
            nested.bind(*binder, name);
            current = *result;
        }
        let protocol = format!("KioCallable_{context}_U{}", root.index());
        let (params, ret) = if let FacadeUse::Function { slots, result, .. } = plan.use_at(current)
        {
            let BoundaryFacadeExecutionUse::Function(layout) = execution.use_at(current) else {
                return Err(prepared_error(
                    "generic Python callable has no prepared execution layout",
                ));
            };
            (
                self.render_callable_params(
                    site,
                    plan,
                    slots,
                    layout,
                    execution,
                    execution_layout,
                    nominals,
                    &nested,
                    &protocol,
                )?,
                self.render_facade_use(
                    site,
                    plan,
                    *result,
                    execution,
                    execution_layout,
                    nominals,
                    &nested,
                    &protocol,
                    false,
                )?,
            )
        } else {
            (
                Vec::new(),
                self.render_facade_use(
                    site,
                    plan,
                    current,
                    execution,
                    execution_layout,
                    nominals,
                    &nested,
                    &protocol,
                    false,
                )?,
            )
        };
        let mut signatures = vec![FnSig {
            params,
            ret,
            suppress_invalid_typevar_use: false,
        }];
        let mut captured = self.root_typevars();
        captured.extend(scope.binders.values().cloned());
        let (locals, arguments) = self.localize_protocol_typevars(
            &format!("Callable_{context}_U{}", root.index()),
            &protocol,
            captured,
            false,
            &mut signatures,
        );
        let signature = signatures.pop().expect("one callable signature");
        let bases = if locals.is_empty() {
            "typing.Protocol".to_owned()
        } else {
            format!("typing.Protocol[{}]", locals.join(", "))
        };
        self.protocol_defs
            .entry(protocol.clone())
            .or_insert_with(|| {
                // A Kio `forall` remains a method-scoped TypeVar even when
                // the binder has only one value occurrence. Pyright otherwise
                // asks to replace that exact binder with `object`; suppress
                // only that widening diagnostic on the generated method.
                format!(
                    "class {protocol}({bases}):\n    def __call__(self{}) -> {ret}: ...  # pyright: ignore[reportInvalidTypeVarUse]\n",
                    positional_method_params(&signature.params),
                    ret = signature.ret,
                )
            });
        Ok(apply_py_type(&protocol, &arguments))
    }

    fn synth_typed_dict(
        &mut self,
        name: &str,
        fields: &[(String, String)],
        scope: &PythonFacadeScope,
    ) -> String {
        let definition_cached = self.shape_defs.contains_key(name);
        let mut params = self.root_typevars();
        params.extend(scope.binders.values().cloned());
        let params = select_live_python_identifiers(
            params,
            fields.iter().map(|(_, annotation)| annotation.as_str()),
        );
        if !definition_cached {
            let all_identifiers = fields.iter().all(|(key, _)| is_plain_identifier(key));
            let definition = if all_identifiers {
                let key = PythonTypedDictDefinition {
                    params: params.clone(),
                    fields: fields.to_vec(),
                };
                if let Some(representative) = self.typed_dict_representatives.get(&key) {
                    // TypedDicts are structural. Keep each site's public name,
                    // but make the checker elaborate an identical body once.
                    // Exact annotation and binder spellings avoid unfolding
                    // recursive types or identifying distinct generic scopes.
                    let definition = format!(
                        "{name}: typing.TypeAlias = {}\n",
                        apply_py_type(representative, &params)
                    );
                    self.shape_defs.insert(name.to_owned(), definition);
                    return apply_py_type(name, &params);
                }
                self.typed_dict_representatives.insert(key, name.to_owned());
                let bases = if params.is_empty() {
                    "typing.TypedDict".to_owned()
                } else {
                    format!("typing.TypedDict, typing.Generic[{}]", params.join(", "))
                };
                let body = fields
                    .iter()
                    .map(|(key, ty)| format!("    {key}: {ty}\n"))
                    .collect::<String>();
                format!("class {name}({bases}):\n{body}")
            } else {
                let base = format!("_{name}Fields");
                let entries = fields
                    .iter()
                    .map(|(key, ty)| format!("{}: {ty}", py_string_literal(key)))
                    .collect::<Vec<_>>()
                    .join(", ");
                if params.is_empty() {
                    format!(
                        "{name} = typing.TypedDict({}, {{{entries}}})\n",
                        py_string_literal(name)
                    )
                } else {
                    format!(
                        "{base} = typing.TypedDict({}, {{{entries}}})\nclass {name}({base}, typing.Generic[{}]):\n    ...\n",
                        py_string_literal(&base),
                        params.join(", ")
                    )
                }
            };
            self.shape_defs.insert(name.to_owned(), definition);
        }
        apply_py_type(name, &params)
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct PythonStubDeclaration {
    name: String,
    source: String,
}

fn shard_python_stub(flat_stub: String) -> Result<PythonStubPackage, EmitError> {
    let declarations = split_python_stub_declarations(&flat_stub)?;
    let shard_count = declarations
        .len()
        .div_ceil(PYTHON_STUB_DECLARATIONS_PER_SHARD);
    let mut owners = BTreeMap::new();
    for (index, declaration) in declarations.iter().enumerate() {
        let owner = index / PYTHON_STUB_DECLARATIONS_PER_SHARD;
        if owners.insert(declaration.name.clone(), owner).is_some() {
            return Err(prepared_error(
                "typed-stub render produced a duplicate top-level declaration",
            ));
        }
    }

    let mut files = BTreeMap::new();
    let mut entrypoint = String::from(
        "# Generated by kio - do not edit by hand.\nfrom __future__ import annotations\n\n",
    );
    for shard in 0..shard_count {
        let module = python_stub_shard_module(shard);
        entrypoint.push_str(&format!("from .{module} import *\n"));

        let start = shard * PYTHON_STUB_DECLARATIONS_PER_SHARD;
        let end = declarations
            .len()
            .min(start + PYTHON_STUB_DECLARATIONS_PER_SHARD);
        let mut dependencies = BTreeSet::new();
        let rendered = declarations[start..end]
            .iter()
            .map(|declaration| {
                rewrite_python_stub_declaration(
                    &declaration.source,
                    shard,
                    &owners,
                    &mut dependencies,
                )
            })
            .collect::<String>();
        let mut content = String::from(PYTHON_STUB_HEADER);
        for dependency in dependencies {
            let dependency = python_stub_shard_module(dependency);
            content.push_str(&format!(
                "from . import {dependency} as {dependency}  # pyright: ignore[reportPrivateUsage]\n"
            ));
        }
        if !rendered.is_empty() {
            if !content.ends_with("\n\n") {
                content.push('\n');
            }
            content.push_str(&rendered);
        }
        files.insert(format!("{module}.pyi"), content);
    }
    files.insert("__init__.pyi".to_owned(), entrypoint);
    Ok(PythonStubPackage { files })
}

fn split_python_stub_declarations(
    flat_stub: &str,
) -> Result<Vec<PythonStubDeclaration>, EmitError> {
    let body = flat_stub
        .strip_prefix(PYTHON_STUB_HEADER)
        .ok_or_else(|| prepared_error("typed-stub render omitted its generated-file header"))?;
    let mut declarations = Vec::new();
    let mut current = String::new();
    for line in body.split_inclusive('\n') {
        if !line.trim().is_empty()
            && !line.starts_with(' ')
            && !line.starts_with('\t')
            && !current.trim().is_empty()
        {
            declarations.push(parse_python_stub_declaration(std::mem::take(&mut current))?);
        }
        current.push_str(line);
    }
    if !current.trim().is_empty() {
        declarations.push(parse_python_stub_declaration(current)?);
    }
    Ok(declarations)
}

fn parse_python_stub_declaration(source: String) -> Result<PythonStubDeclaration, EmitError> {
    let line = source
        .lines()
        .find(|line| !line.trim().is_empty())
        .ok_or_else(|| prepared_error("typed-stub render produced an empty declaration"))?
        .trim_start();
    let name_source = line
        .strip_prefix("class ")
        .or_else(|| line.strip_prefix("def "))
        .unwrap_or(line);
    let name_len = name_source
        .bytes()
        .take_while(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
        .count();
    if name_len == 0 {
        return Err(prepared_error(
            "typed-stub render produced an unrecognized top-level declaration",
        ));
    }
    Ok(PythonStubDeclaration {
        name: name_source[..name_len].to_owned(),
        source,
    })
}

fn python_stub_shard_module(index: usize) -> String {
    format!("_kio_stub_{index:04}")
}

fn rewrite_python_stub_declaration(
    source: &str,
    shard: usize,
    owners: &BTreeMap<String, usize>,
    dependencies: &mut BTreeSet<usize>,
) -> String {
    source
        .split_inclusive('\n')
        .map(|line| rewrite_python_stub_line(line, shard, owners, dependencies))
        .collect()
}

fn rewrite_python_stub_line(
    line: &str,
    shard: usize,
    owners: &BTreeMap<String, usize>,
    dependencies: &mut BTreeSet<usize>,
) -> String {
    let protected = python_stub_binding_range(line);
    let bytes = line.as_bytes();
    let mut rendered = String::with_capacity(line.len());
    let mut copied_through = 0;
    let mut uses_private_cross_shard_name = false;
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at] == b'#' {
            break;
        }
        if bytes[at] == b'\'' || bytes[at] == b'"' {
            let quote = bytes[at];
            at += 1;
            while at < bytes.len() {
                if bytes[at] == b'\\' {
                    at = (at + 2).min(bytes.len());
                } else if bytes[at] == quote {
                    at += 1;
                    break;
                } else {
                    at += 1;
                }
            }
            continue;
        }
        if bytes[at].is_ascii_alphabetic() || bytes[at] == b'_' {
            let start = at;
            at += 1;
            while at < bytes.len() && (bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_') {
                at += 1;
            }
            let is_binding = protected.is_some_and(|(from, to)| start >= from && at <= to);
            let is_qualified_member = start > 0 && bytes[start - 1] == b'.';
            if !is_binding
                && !is_qualified_member
                && let Some(owner) = owners.get(&line[start..at])
                && *owner != shard
            {
                dependencies.insert(*owner);
                rendered.push_str(&line[copied_through..start]);
                rendered.push_str(&python_stub_shard_module(*owner));
                rendered.push('.');
                rendered.push_str(&line[start..at]);
                copied_through = at;
                // Ignoring the private-module import makes its public attributes
                // ordinary sibling references. Only an underscore-prefixed support
                // declaration remains a private use at the annotation site itself.
                uses_private_cross_shard_name |= line[start..at].starts_with('_');
            }
        } else {
            at += 1;
        }
    }
    rendered.push_str(&line[copied_through..]);
    if uses_private_cross_shard_name {
        add_pyright_suppression(rendered, "reportPrivateUsage")
    } else {
        rendered
    }
}

fn add_pyright_suppression(mut line: String, diagnostic: &str) -> String {
    // The shard modules and some generated support declarations are deliberately
    // private. Pyright otherwise diagnoses their sibling-shard transport as a
    // public API access, so keep that exception on the exact generated line while
    // leaving its annotation and every unrelated diagnostic under strict checking.
    let newline = if line.ends_with('\n') {
        line.pop();
        "\n"
    } else {
        ""
    };
    const PREFIX: &str = "  # pyright: ignore[";
    if let Some(directive) = line.rfind(PREFIX)
        && line.ends_with(']')
    {
        let closing = line.len() - 1;
        let diagnostics = &line[directive + PREFIX.len()..closing];
        if !diagnostics.split(',').any(|item| item.trim() == diagnostic) {
            line.insert_str(closing, &format!(", {diagnostic}"));
        }
    } else {
        line.push_str(PREFIX);
        line.push_str(diagnostic);
        line.push(']');
    }
    line.push_str(newline);
    line
}

fn python_stub_binding_range(line: &str) -> Option<(usize, usize)> {
    let bytes = line.as_bytes();
    let mut at = bytes.iter().position(|byte| !byte.is_ascii_whitespace())?;
    for keyword in ["class", "def"] {
        if line[at..].starts_with(keyword)
            && bytes
                .get(at + keyword.len())
                .is_some_and(u8::is_ascii_whitespace)
        {
            at += keyword.len();
            while bytes.get(at).is_some_and(u8::is_ascii_whitespace) {
                at += 1;
            }
            let end = python_identifier_end(bytes, at);
            return (end > at).then_some((at, end));
        }
    }
    let end = python_identifier_end(bytes, at);
    if end == at {
        return None;
    }
    let mut after = end;
    while bytes.get(after).is_some_and(u8::is_ascii_whitespace) {
        after += 1;
    }
    matches!(bytes.get(after), Some(b':') | Some(b'=')).then_some((at, end))
}

fn python_identifier_end(bytes: &[u8], mut at: usize) -> usize {
    if !bytes
        .get(at)
        .is_some_and(|byte| byte.is_ascii_alphabetic() || *byte == b'_')
    {
        return at;
    }
    at += 1;
    while bytes
        .get(at)
        .is_some_and(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
    {
        at += 1;
    }
    at
}

