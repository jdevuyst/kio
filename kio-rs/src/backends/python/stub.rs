fn python_identifier_occurrences(annotation: &str, identifier: &str) -> usize {
    let mut occurrences = 0;
    visit_python_identifiers(annotation, |token| {
        if token == identifier {
            occurrences += 1;
        }
    });
    occurrences
}

fn visit_python_identifiers(annotation: &str, mut visit: impl FnMut(&str)) {
    let bytes = annotation.as_bytes();
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_' {
            let start = at;
            at += 1;
            while at < bytes.len() && (bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_') {
                at += 1;
            }
            visit(&annotation[start..at]);
        } else {
            at += 1;
        }
    }
}

fn replace_python_identifiers(annotation: &str, replacements: &BTreeMap<String, String>) -> String {
    let bytes = annotation.as_bytes();
    let mut rendered = String::with_capacity(annotation.len());
    let mut copied_through = 0;
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_' {
            let start = at;
            at += 1;
            while at < bytes.len() && (bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_') {
                at += 1;
            }
            #[cfg(test)]
            record_python_stub_batch_work(|work| {
                work.protocol_rendered_identifiers += 1;
            });
            if let Some(replacement) = replacements.get(&annotation[start..at]) {
                rendered.push_str(&annotation[copied_through..start]);
                rendered.push_str(replacement);
                copied_through = at;
            }
        } else {
            at += 1;
        }
    }
    rendered.push_str(&annotation[copied_through..]);
    rendered
}

fn select_live_python_identifiers<'a>(
    candidates: Vec<String>,
    annotations: impl IntoIterator<Item = &'a str>,
) -> Vec<String> {
    let mut seen = BTreeSet::new();
    let candidates = candidates
        .into_iter()
        .filter(|candidate| seen.insert(candidate.clone()))
        .collect::<Vec<_>>();
    if candidates.is_empty() {
        return candidates;
    }
    #[cfg(test)]
    record_python_stub_batch_work(|work| {
        work.typed_dict_candidate_visits += candidates.len();
    });
    let live = {
        let by_name = candidates
            .iter()
            .enumerate()
            .map(|(index, candidate)| (candidate.as_str(), index))
            .collect::<BTreeMap<_, _>>();
        let mut live = vec![false; candidates.len()];
        for annotation in annotations {
            visit_python_identifiers(annotation, |identifier| {
                #[cfg(test)]
                record_python_stub_batch_work(|work| {
                    work.typed_dict_identifier_visits += 1;
                });
                if let Some(index) = by_name.get(identifier) {
                    live[*index] = true;
                }
            });
        }
        live
    };
    candidates
        .into_iter()
        .zip(live)
        .filter_map(|(candidate, live)| live.then_some(candidate))
        .collect::<Vec<_>>()
}

