/// The Python type for a `role(...)` atomic, per `specs/backends/python.md`
/// § FFI surface. Every integer role is Python `int` (arbitrary precision,
/// so no narrow / wide split as in JS); floats are `float`; `str` is
/// `str`; `bool` is `bool`.
fn role_to_py_type(role: Role) -> &'static str {
    match role {
        Role::Str => "str",
        Role::Bool => "bool",
        Role::I8
        | Role::I16
        | Role::I32
        | Role::I64
        | Role::I128
        | Role::U8
        | Role::U16
        | Role::U32
        | Role::U64
        | Role::U128 => "int",
        Role::F32 | Role::F64 => "float",
    }
}

/// Whether `name` can be written as a Python class member (attribute or
/// method): a plain identifier that is not a hard keyword. Kio leaf names
/// are always identifiers, so only the hard-keyword case escapes.
fn is_spellable(name: &str) -> bool {
    is_plain_identifier(name) && !is_python_keyword(name)
}

/// Whether `s` is a plain ASCII Python identifier (the subset Kio names
/// occupy). Does not exclude keywords — [`is_spellable`] layers that on.
fn is_plain_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// A single-quoted Python string literal for a `TypedDict` functional-form
/// key or name. Keys are Kio identifiers or the qualified `<path>.<F>`
/// spelling, so only quote / backslash need escaping; guard both.
fn py_string_literal(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

