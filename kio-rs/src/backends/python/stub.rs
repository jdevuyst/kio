    #[test]
    fn sealed_history_keeps_mixed_python_artifacts_live_only() {
        let pkg = build_package(
            &["module api; \
               host type Live role(str); \
               host type Live_box[A]; \
               pub newtype Live_token[A] : A { \
                 pub constructor make_live_token; \
                 projector read_live_token; \
               }; \
               host fn current(value: Live & Live_box(Live_token(.))) -> Live; \
               pub fn echo(value: Live) -> Live { value }"],
            "bridge { api; }",
        );
        let signature = crate::pass::parser::parse_signature_file(
            r#"signature pkg v(3);
v(1) {
  nonbreaking {
    add {
      module api {
        host type Retired role(i32);
        host type Retired_box[A];
        newtype Retired_token[A] : A {
          pub constructor make_retired_token;
          projector read_retired_token;
        };
        host fn old(value: Retired & Retired_box(Retired_token(.))) -> Retired;
      }
    }
  }
}
v(2) {
  nonbreaking {
    remove {
      module api {
        Retired;
        Retired_box;
        Retired_token;
        old;
      }
    }
  }
}
"#,
            None,
        )
        .expect("parse mixed Python history signature");
        let replayed = crate::sig::replay(&signature).expect("replay mixed Python history");
        let history = (3, replayed);

        let live_stub = lower_package_to_stub(&pkg, "greeter").expect("render live Python stub");
        let retained_stub = lower_package_to_stub_with_signature(&pkg, "greeter", Some(&history))
            .expect("render Python stub with sealed history");
        let live_runtime = crate::backends::python::emit::lower_package_to_module(&pkg, "greeter")
            .expect("render live Python runtime");
        let retained_runtime =
            crate::backends::python::emit::lower_package_to_module_with_signature(
                &pkg,
                "greeter",
                Some(&history),
            )
            .expect("render Python runtime with sealed history");

        for declaration in [
            "KioHost_V1_M1_C3_apiN4_Live = typing.TypeVar",
            "KioHostParam_V1_M1_C3_apiN7_LiveBox_0 = typing.TypeVar",
            "class KioHostType_V1_M1_C3_apiN7_LiveBox(",
            "KioNewtypeParam_V1_M1_C3_apiN9_LiveToken_0 = typing.TypeVar",
            "class KioNewtype_V1_M1_C3_apiN9_LiveToken(",
            "def KioHostIn_api_Live(",
            "def KioHostOut_api_Live(",
            "def current(",
        ] {
            assert!(
                retained_stub.contains(declaration),
                "live Python declaration is absent: {declaration}\n{retained_stub}"
            );
        }
        for retired in ["Retired", "Retired_box", "Retired_token", "def old("] {
            assert!(
                !retained_stub.contains(retired),
                "history-only Python stub declaration survived: {retired}\n{retained_stub}"
            );
            assert!(
                !retained_runtime.contains(retired),
                "history-only Python runtime declaration survived: {retired}\n{retained_runtime}"
            );
        }
        assert!(
            !retained_runtime.contains("\"live\":"),
            "the live-only Python runtime retained a history-origin flag:\n{retained_runtime}"
        );
        for declaration in [
            "\"name\":\"Live\"",
            "\"name\":\"Live_box\"",
            "\"frame\":\"V1_M1_C3_apiN7_LiveBox\"",
            "\"name\":\"Live_token\"",
            "\"name\":\"current\"",
            "\"name\":\"echo\"",
        ] {
            assert!(
                retained_runtime.contains(declaration),
                "live Python runtime declaration is absent: {declaration}\n{retained_runtime}"
            );
        }
        assert_eq!(
            live_stub, retained_stub,
            "sealed history changed the live-only Python stub"
        );
        assert_eq!(
            live_runtime, retained_runtime,
            "sealed history changed the live-only Python runtime"
        );
    }
