// Fixed-purpose Kiodoc lexical rules shared by the compiler and editor grammars.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

export const rules = {
  bracket: { open: '[`', close: '`]', forbidden: ['`', ']', '\n'], directive: '@' },
  inline: { escape: '\\', code: '`', labelOpen: '[', labelClose: ']', destinationOpen: '(', destinationClose: ')', definition: ':' },
  directives: [['Signature', 'signature'], ['Source', 'source'], ['Type', 'type']],
  emphasis: ['*', '_'],
  kioLanguage: 'kio',
  attrs: { open: '{', close: '}', selfRef: '@', whitespace: [' ', '\t', '\r', '\n'] },
  paragraph: { code: ['`', '~'], minFence: 3, heading: '#', maxHeading: 6,
    thematic: ['-', '*', '_'], quote: '>', list: ['-', '*', '+'], ordered: ['.', ')'] },
  fence: {
    marker: '`', minWidth: 3, maxIndent: 3,
    hiddenOpen: '<!--', hiddenClose: '-->',
    visibleOpen: 'leading <= max_indent && width >= min_width && !rest_marker',
    visibleClose: 'leading <= max_indent && rest_ws',
  },
  // Unicode White_Space; the compiler test checks the native character property.
  whitespace: [9, 10, 11, 12, 13, 32, 133, 160, 5760, 8192, 8193, 8194,
    8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288],
  transitions: [
    ['s.disabled', 'PROSE', 'UNCHANGED'],
    ['s.mode == 1 && f.close_visible && f.width >= s.width', 'CLOSE', 'RESET'],
    ['s.mode == 1', 'CODE', 'UNCHANGED'],
    ['s.mode == 2 && f.close_hidden', 'CLOSE', 'RESET'],
    ['s.mode == 2', 'CODE', 'UNCHANGED'],
    ['f.open_visible', 'OPEN', 'VISIBLE'],
    ['f.open_hidden && hidden_closed', 'HIDDEN', 'HIDDEN'],
    ['f.open_hidden', 'UNTERMINATED', 'DISABLED'],
  ],
};

const quote = JSON.stringify;
const rustChar = c => `'${c.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n').replaceAll('\r', '\\r').replaceAll('\t', '\\t')}'`;
const header = '// Generated by tools/kiodoc-grammar/generate.mjs.\n';

export function rustRules() {
  const f = rules.fence;
  return `${header}
#[derive(Debug, Clone, Copy)]
pub(crate) struct FenceFacts {
    pub(crate) leading: usize,
    pub(crate) width: usize,
    pub(crate) marker_end: usize,
    pub(crate) open_visible: bool,
    pub(crate) close_visible: bool,
    pub(crate) open_hidden: bool,
    pub(crate) close_hidden: bool,
}

pub(crate) fn whitespace(c: char) -> bool {
    matches!(c as u32, ${rules.whitespace.join(' | ')})
}

pub(crate) fn fence_facts(line: &str) -> FenceFacts {
    let max_indent = ${f.maxIndent};
    let min_width = ${f.minWidth};
    let leading = line.bytes().take_while(|&b| b == b' ').count();
    let width = line[leading..].bytes().take_while(|&b| b == b'${f.marker}').count();
    let marker_end = leading + width;
    let rest = &line[marker_end..];
    let rest_marker = rest.contains(${rustChar(f.marker)});
    let rest_ws = rest.chars().all(whitespace);
    let open_hidden = line.strip_prefix(${quote(f.hiddenOpen)}).is_some_and(|rest| {
        rest.as_bytes().first().is_some_and(u8::is_ascii_alphabetic)
            && !rest.contains(${quote(f.hiddenClose)})
    });
    FenceFacts {
        leading, width, marker_end,
        open_visible: ${f.visibleOpen},
        close_visible: ${f.visibleClose},
        open_hidden,
        close_hidden: line.trim_matches(whitespace) == ${quote(f.hiddenClose)},
    }
}

pub(crate) fn bracket_bounds(source: &str, start: usize) -> Option<(usize, usize, bool)> {
    let suffix = source.get(start..)?.strip_prefix(${quote(rules.bracket.open)})?;
    let payload = start + ${Buffer.byteLength(rules.bracket.open)};
    let end = suffix.find([${rules.bracket.forbidden.map(rustChar).join(', ')}])
        .map_or(source.len(), |offset| payload + offset);
    let complete = source[end..].starts_with(${quote(rules.bracket.close)});
    if !complete && end != source.len() && source.as_bytes()[end] != b'\\n' {
        return None;
    }
    Some((payload, end, complete))
}

pub(crate) fn link_bounds(source: &str, start: usize) -> Option<(usize, usize)> {
    LinkCursor::new(source).bounds(start)
}

/// Reuse monotonically advancing delimiter searches within one source slice.
pub(crate) struct LinkCursor<'a> {
    source: &'a str,
    next_label: usize,
    next_destination: usize,
}
#[cfg(test)]
thread_local! { pub(crate) static LINK_SEARCH_BYTES: std::cell::Cell<usize> = const { std::cell::Cell::new(0) }; }
impl<'a> LinkCursor<'a> {
    pub(crate) fn new(source: &'a str) -> Self {
        Self { source, next_label: 0, next_destination: 0 }
    }
    pub(crate) fn bounds(&mut self, start: usize) -> Option<(usize, usize)> {
        self.source.get(start..)?.strip_prefix(${quote(rules.inline.labelOpen)})?;
        let from = start + 1;
        if self.next_label < from {
            self.next_label = self.source[from..].find(${rustChar(rules.inline.labelClose)})
                .map_or(self.source.len(), |offset| from + offset);
            #[cfg(test)] LINK_SEARCH_BYTES.with(|count| count.set(count.get() + self.next_label - from + usize::from(self.next_label < self.source.len())));
        }
        let close_label = self.next_label;
        if close_label == self.source.len()
            || !self.source[close_label + 1..].starts_with(${quote(rules.inline.destinationOpen)}) { return None; }
        let from = close_label + 2;
        if self.next_destination < from {
            self.next_destination = self.source[from..].find(${rustChar(rules.inline.destinationClose)})
                .map_or(self.source.len(), |offset| from + offset);
            #[cfg(test)] LINK_SEARCH_BYTES.with(|count| count.set(count.get() + self.next_destination - from + usize::from(self.next_destination < self.source.len())));
        }
        (self.next_destination < self.source.len()).then_some((close_label, self.next_destination))
    }
}

pub(crate) fn definition_bounds(line: &str) -> Option<(usize, usize)> {
    let trimmed = line.trim();
    let rest = trimmed.strip_prefix(${rustChar(rules.inline.labelOpen)})?;
    if rest.starts_with(${rustChar(rules.inline.code)}) { return None; }
    let close = rest.find(${rustChar(rules.inline.labelClose)})?;
    if !rest[close + 1..].trim_start().starts_with(${rustChar(rules.inline.definition)}) { return None; }
    let untrimmed = &rest[..close];
    let key = untrimmed.trim();
    if key.is_empty() { return None; }
    let start = line.len() - line.trim_start().len() + 1 + untrimmed.len() - untrimmed.trim_start().len();
    Some((start, start + key.len()))
}

pub(crate) const INLINE_ESCAPE: u8 = b${rustChar(rules.inline.escape)};
pub(crate) const INLINE_CODE: u8 = b${rustChar(rules.inline.code)};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct EmphasisBounds { pub(crate) width: usize, pub(crate) end: usize }
pub(crate) struct EmphasisCursor<'a> { source: &'a str, next: [usize; ${rules.emphasis.length * 2}] }
impl<'a> EmphasisCursor<'a> {
    pub(crate) fn new(source: &'a str) -> Self { Self { source, next: [0; ${rules.emphasis.length * 2}] } }
    pub(crate) fn bounds(&mut self, start: usize) -> Option<EmphasisBounds> {
        let rest = self.source.get(start..)?;
        let first = *rest.as_bytes().first()?;
        let marker = b${quote(rules.emphasis.join(''))}.iter().position(|&c| c == first)?;
        for width in [2, 1] {
            if width == 2 && rest.as_bytes().get(1) != Some(&first) { continue; }
            let from = start + width;
            let slot = marker * 2 + width - 1;
            if self.next[slot] < from {
                self.next[slot] = self.source[from..].find(&rest[..width])
                    .map_or(self.source.len(), |at| from + at);
            }
            let close = self.next[slot];
            if close == self.source.len() { continue; }
            if width == 1 && (close == from || self.source.as_bytes()[from] == b' ') { return None; }
            return Some(EmphasisBounds { width, end: close + width });
        }
        None
    }
}

pub(crate) fn list_marker(line: &str) -> Option<usize> {
    let bytes = line.as_bytes();
    if bytes.first().is_some_and(|b| b${quote(rules.paragraph.list.join(''))}.contains(b))
        && bytes.get(1) == Some(&b' ') { return Some(2); }
    let digits = bytes.iter().take_while(|b| b.is_ascii_digit()).count();
    (digits > 0 && bytes.get(digits).is_some_and(|b| b${quote(rules.paragraph.ordered.join(''))}.contains(b))
        && bytes.get(digits + 1) == Some(&b' ')).then_some(digits + 2)
}

pub(crate) fn quote_marker(line: &str) -> Option<usize> {
    line.strip_prefix(${rustChar(rules.paragraph.quote)}).map(|rest| 1 + usize::from(rest.starts_with(' ')))
}

pub(crate) fn fence_info_parts(info: &str) -> (&str, &str) {
    let trimmed = info.trim_start();
    let split = trimmed.find(char::is_whitespace).unwrap_or(trimmed.len());
    let (language, rest) = trimmed.split_at(split);
    (language, rest.trim())
}

pub(crate) fn is_kio_info(info: &str) -> bool { fence_info_parts(info).0 == ${quote(rules.kioLanguage)} }

pub(crate) fn attr_whitespace(byte: u8) -> bool {
    b${quote(rules.attrs.whitespace.join(''))}.contains(&byte)
}
pub(crate) fn bare_self_ref_end(next: Option<u8>) -> bool {
    next.is_none_or(|byte| byte == b${rustChar(rules.attrs.close)} || attr_whitespace(byte))
}
pub(crate) fn self_harness_info(info: &str) -> bool {
    let (language, attrs) = fence_info_parts(info);
    if language != ${quote(rules.kioLanguage)} { return false; }
    let Some(rest) = attrs.strip_prefix(${rustChar(rules.attrs.open)}) else { return false; };
    let rest = rest.trim_start_matches(|c: char| c.is_ascii() && attr_whitespace(c as u8));
    rest.strip_prefix(${rustChar(rules.attrs.selfRef)}).is_some_and(|tail| bare_self_ref_end(tail.as_bytes().first().copied()))
}

pub(crate) fn thematic_break(line: &str) -> bool {
    for marker in [${rules.paragraph.thematic.map(rustChar).join(',')}] {
        let mut count = 0;
        if line.chars().filter(|c| !c.is_whitespace()).all(|c| { count += 1; c == marker })
            && count >= 3 { return true; }
    }
    false
}

pub(crate) fn inline_heading(line: &str) -> bool {
    let width = line.bytes().take_while(|&b| b == b${rustChar(rules.paragraph.heading)}).count();
    width > 0 && width <= ${rules.paragraph.maxHeading}
        && (width == line.len() || line.as_bytes()[width] == b' ')
}

pub(crate) fn inline_break(line: &str) -> bool {
    let line = line.trim_start();
    let bytes = line.as_bytes();
    if line.is_empty() || inline_heading(line) || line.starts_with(${rustChar(rules.paragraph.quote)}) { return true; }
    if bytes[0] == b'<' && bytes.get(1).is_some_and(|b| b.is_ascii_alphabetic() || *b == b'/') { return true; }
    if b${quote(rules.paragraph.code.join(''))}.contains(&bytes[0])
        && bytes.iter().take_while(|&&b| b == bytes[0]).count() >= ${rules.paragraph.minFence} { return true; }
    for marker in [${rules.paragraph.thematic.map(rustChar).join(',')}] {
        let mut chars = line.chars().filter(|c| !c.is_whitespace()).peekable();
        if chars.peek() == Some(&marker) && chars.all(|c| c == marker)
            && line.chars().filter(|c| !c.is_whitespace()).count() >= 3 { return true; }
    }
    if b${quote(rules.paragraph.list.join(''))}.contains(&bytes[0]) && bytes.get(1) == Some(&b' ') { return true; }
    let digits = bytes.iter().take_while(|b| b.is_ascii_digit()).count();
    digits > 0 && bytes.get(digits).is_some_and(|b| b${quote(rules.paragraph.ordered.join(''))}.contains(b))
        && bytes.get(digits + 1) == Some(&b' ')
}

/// Kiodoc directive vocabulary; recognition does not resolve its operand.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DirectiveKeyword { ${rules.directives.map(([variant]) => variant).join(', ')} }
impl DirectiveKeyword {
    pub(crate) const ALL: &'static [Self] = &[${rules.directives.map(([variant]) => `Self::${variant}`).join(', ')}];
    pub fn parse(s: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|keyword| keyword.as_str() == s)
    }
    pub fn as_str(self) -> &'static str {
        match self { ${rules.directives.map(([variant, text]) => `Self::${variant} => ${quote(text)},`).join(' ')} }
    }
}
`;
}

// Character-oriented Tree-sitter glue supplies the line; these decisions are
// the same generated predicates consumed by the canonical Rust fence scanner.
export function cRules() {
  const f = rules.fence;
  const chars = s => [...s].map(c => c.codePointAt(0)).join(', ');
  const states = {
    UNCHANGED: 's', RESET: '(KioDocState){0, 0, false, s.active}',
    VISIBLE: '(KioDocState){1, f.width, false, s.active}',
    HIDDEN: '(KioDocState){2, 0, false, s.active}',
    DISABLED: '(KioDocState){0, 0, true, s.active}',
  };
  const transitions = rules.transitions.map(([condition, kind, state]) =>
    `  if (${condition}) return (KioDocStep){KIO_DOC_${kind}, ${states[state]}};`).join('\n');
  return `${header}
#ifndef KIO_DOC_RULES_H
#define KIO_DOC_RULES_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#define KIO_DOC_FENCE_MARKER ${f.marker.codePointAt(0)}
#define KIO_DOC_HIDDEN_OPEN_FIRST ${f.hiddenOpen.codePointAt(0)}
#define KIO_DOC_HIDDEN_OPEN_WIDTH ${[...f.hiddenOpen].length}
#define KIO_DOC_DIRECTIVE_MARKER ${rules.bracket.directive.codePointAt(0)}
#define KIO_DOC_BRACKET_CLOSE_WIDTH ${[...rules.bracket.close].length}
#define KIO_DOC_LINK_OPEN ${rules.inline.destinationOpen.codePointAt(0)}
#define KIO_DOC_LABEL_OPEN ${rules.inline.labelOpen.codePointAt(0)}
#define KIO_DOC_LABEL_CLOSE ${rules.inline.labelClose.codePointAt(0)}
#define KIO_DOC_INLINE_CODE_MARKER ${rules.inline.code.codePointAt(0)}
${cInlineRules()}
typedef struct {
  size_t leading, width, marker_end;
  bool open_visible, close_visible, open_hidden, close_hidden;
} KioDocFenceFacts;
static bool kio_doc_whitespace(uint32_t c) {
  switch (c) { ${rules.whitespace.map(c => `case ${c}:`).join(' ')} return true; default: return false; }
}
static bool kio_doc_prefix(const uint32_t *s, size_t n, const uint32_t *p, size_t m) {
  if (n < m) return false;
  for (size_t i = 0; i < m; i++) if (s[i] != p[i]) return false;
  return true;
}
static KioDocFenceFacts kio_doc_fence_facts(const uint32_t *s, size_t n) {
  const size_t max_indent = ${f.maxIndent}, min_width = ${f.minWidth};
  size_t leading = 0;
  while (leading < n && s[leading] == 32) leading++;
  size_t end = leading;
  while (end < n && s[end] == ${f.marker.codePointAt(0)}) end++;
  size_t width = end - leading;
  bool rest_marker = false, rest_ws = true;
  for (size_t i = end; i < n; i++) {
    rest_marker |= s[i] == ${f.marker.codePointAt(0)};
    rest_ws &= kio_doc_whitespace(s[i]);
  }
  const uint32_t open[] = { ${chars(f.hiddenOpen)} }, close[] = { ${chars(f.hiddenClose)} };
  bool hidden = kio_doc_prefix(s, n, open, ${f.hiddenOpen.length}) && n > ${f.hiddenOpen.length}
    && ((s[${f.hiddenOpen.length}] >= 65 && s[${f.hiddenOpen.length}] <= 90)
      || (s[${f.hiddenOpen.length}] >= 97 && s[${f.hiddenOpen.length}] <= 122));
  for (size_t i = 0; i < n; i++) if (kio_doc_prefix(s+i, n-i, close, ${f.hiddenClose.length})) hidden = false;
  size_t a = 0, b = n;
  while (a < b && kio_doc_whitespace(s[a])) a++;
  while (b > a && kio_doc_whitespace(s[b-1])) b--;
  return (KioDocFenceFacts){leading, width, end,
    ${f.visibleOpen}, ${f.visibleClose}, hidden,
    b-a == ${f.hiddenClose.length} && kio_doc_prefix(s+a, b-a, close, ${f.hiddenClose.length})};
}
enum { KIO_DOC_PROSE, KIO_DOC_OPEN, KIO_DOC_CODE, KIO_DOC_CLOSE, KIO_DOC_HIDDEN, KIO_DOC_UNTERMINATED };
typedef struct { uint8_t mode; uint64_t width; bool disabled, active; } KioDocState;
typedef struct { int kind; KioDocState state; } KioDocStep;
static KioDocStep kio_doc_step(KioDocState s, KioDocFenceFacts f, bool hidden_closed) {
${transitions}
  return (KioDocStep){KIO_DOC_PROSE, s};
}
#endif
`;
}

// Index units are Unicode scalars in C, UTF-8 bytes in Rust. Both callers
// convert these original-input boundaries, never rewritten display text.
function cInlineRules() {
  const i = rules.inline, p = rules.paragraph;
  const cp = s => s.codePointAt(0);
  return `
typedef struct { bool found; size_t start, end; bool complete; } KioDocBounds;
static bool kio_doc_whitespace(uint32_t c);
static bool kio_doc_inline_start(uint32_t c) { return ${[i.escape, i.code, i.labelOpen].map(ch => `c == ${cp(ch)}`).join(' || ')}; }
static bool kio_doc_ascii_alpha(uint32_t c) { return (c >= 65 && c <= 90) || (c >= 97 && c <= 122); }
static bool kio_doc_ascii_punctuation(uint32_t c) { return (c >= 33 && c <= 47) || (c >= 58 && c <= 64) || (c >= 91 && c <= 96) || (c >= 123 && c <= 126); }
typedef struct { size_t width, end; } KioDocEmphasis;
static bool kio_doc_emphasis_marker(uint32_t c) { return ${rules.emphasis.map(c => `c == ${cp(c)}`).join(' || ')}; }
static KioDocEmphasis kio_doc_emphasis_bounds(const uint32_t *s, size_t n, size_t start) {
  if (start >= n || !kio_doc_emphasis_marker(s[start])) return (KioDocEmphasis){0};
  for (size_t width = 2; width; width--) {
    if (width == 2 && (start+1 >= n || s[start+1] != s[start])) continue;
    for (size_t close = start+width; close+width <= n; close++) {
      if (s[close] != s[start] || (width == 2 && s[close+1] != s[start])) continue;
      if (width == 1 && (close == start+1 || s[start+1] == 32)) return (KioDocEmphasis){0};
      return (KioDocEmphasis){width,close+width};
    }
  }
  return (KioDocEmphasis){0};
}
static bool kio_doc_emphasis_decided(const uint32_t *s, size_t n, bool boundary) {
  if (boundary || !n || !kio_doc_emphasis_marker(s[0])) return true;
  if (n == 1) return false;
  KioDocEmphasis found = kio_doc_emphasis_bounds(s,n,0);
  if (s[1] == s[0]) return found.width == 2;
  return found.width || s[1] == 32;
}
static bool kio_doc_thematic_break(const uint32_t *s, size_t n) {
  const uint32_t markers[] = {${p.thematic.map(cp).join(',')}};
  for (size_t m = 0; m < sizeof(markers)/sizeof(*markers); m++) {
    size_t count = 0; bool matches = true;
    for (size_t j = 0; j < n; j++) if (!kio_doc_whitespace(s[j])) { count++; matches &= s[j] == markers[m]; }
    if (matches && count >= 3) return true;
  }
  return false;
}
static size_t kio_doc_list_marker(const uint32_t *s, size_t n) {
  if (n > 1 && (${p.list.map(c => `s[0] == ${cp(c)}`).join(' || ')}) && s[1] == 32) return 2;
  size_t digits = 0; while (digits < n && s[digits] >= 48 && s[digits] <= 57) digits++;
  return digits && digits+1 < n && (${p.ordered.map(c => `s[digits] == ${cp(c)}`).join(' || ')}) && s[digits+1] == 32 ? digits+2 : 0;
}
static size_t kio_doc_quote_marker(const uint32_t *s, size_t n) {
  return n && s[0] == ${cp(p.quote)} ? 1 + (n > 1 && s[1] == 32) : 0;
}
static bool kio_doc_is_kio_info(const uint32_t *s, size_t n) {
  size_t a = 0; while (a < n && kio_doc_whitespace(s[a])) a++;
  const uint32_t word[] = {${[...rules.kioLanguage].map(cp).join(',')}};
  const size_t width = sizeof(word)/sizeof(*word);
  if (n-a < width) return false;
  for (size_t j = 0; j < width; j++) if (s[a+j] != word[j]) return false;
  return a+width == n || kio_doc_whitespace(s[a+width]);
}
static bool kio_doc_attr_whitespace(uint32_t c) { return ${rules.attrs.whitespace.map(c => `c == ${cp(c)}`).join(' || ')}; }
static bool kio_doc_self_harness_info(const uint32_t *s, size_t n) {
  if (!kio_doc_is_kio_info(s,n)) return false;
  size_t a = 0; while (a < n && kio_doc_whitespace(s[a])) a++;
  while (a < n && !kio_doc_whitespace(s[a])) a++;
  while (a < n && kio_doc_whitespace(s[a])) a++;
  if (a == n || s[a++] != ${cp(rules.attrs.open)}) return false;
  while (a < n && kio_doc_attr_whitespace(s[a])) a++;
  if (a == n || s[a++] != ${cp(rules.attrs.selfRef)}) return false;
  return a == n || s[a] == ${cp(rules.attrs.close)} || kio_doc_attr_whitespace(s[a]);
}
static KioDocBounds kio_doc_bracket_bounds(const uint32_t *s, size_t n, size_t start) {
  if (start + 1 >= n || s[start] != ${cp(rules.bracket.open)} || s[start+1] != ${cp(rules.bracket.open[1])}) return (KioDocBounds){0};
  size_t end = start + 2;
  while (end < n && ${rules.bracket.forbidden.map(c => `s[end] != ${cp(c)}`).join(' && ')}) end++;
  bool complete = end + 1 < n && s[end] == ${cp(rules.bracket.close)} && s[end+1] == ${cp(rules.bracket.close[1])};
  if (!complete && end < n && s[end] != 10) return (KioDocBounds){0};
  return (KioDocBounds){true, start+2, end, complete};
}
static KioDocBounds kio_doc_link_bounds(const uint32_t *s, size_t n, size_t start) {
  if (start >= n || s[start] != ${cp(i.labelOpen)}) return (KioDocBounds){0};
  size_t close = start + 1;
  while (close < n && s[close] != ${cp(i.labelClose)}) close++;
  if (close + 1 >= n || s[close+1] != ${cp(i.destinationOpen)}) return (KioDocBounds){0};
  size_t end = close + 2;
  while (end < n && s[end] != ${cp(i.destinationClose)}) end++;
  return end < n ? (KioDocBounds){true, close, end, true} : (KioDocBounds){0};
}
static KioDocBounds kio_doc_definition_bounds(const uint32_t *s, size_t n) {
  size_t start = 0;
  while (start < n && kio_doc_whitespace(s[start])) start++;
  if (start >= n || s[start++] != ${cp(i.labelOpen)} || start >= n || s[start] == ${cp(i.code)}) return (KioDocBounds){0};
  size_t end = start;
  while (end < n && s[end] != ${cp(i.labelClose)}) end++;
  if (end == n) return (KioDocBounds){0};
  size_t after = end+1;
  while (after < n && kio_doc_whitespace(s[after])) after++;
  if (after == n || s[after] != ${cp(i.definition)}) return (KioDocBounds){0};
  while (start < end && kio_doc_whitespace(s[start])) start++;
  while (end > start && kio_doc_whitespace(s[end-1])) end--;
  return (KioDocBounds){start < end, start, end, true};
}
static bool kio_doc_inline_heading(const uint32_t *s, size_t n) {
  size_t width = 0;
  while (width < n && s[width] == ${cp(p.heading)}) width++;
  return width > 0 && width <= ${p.maxHeading} && (width == n || s[width] == 32);
}
static bool kio_doc_inline_break(const uint32_t *s, size_t n) {
  while (n && kio_doc_whitespace(*s)) { s++; n--; }
  if (!n || kio_doc_inline_heading(s,n) || s[0] == ${cp(p.quote)}) return true;
  if (n > 1 && s[0] == 60 && (kio_doc_ascii_alpha(s[1]) || s[1] == 47)) return true;
  if (${p.code.map(c => `s[0] == ${cp(c)}`).join(' || ')}) {
    size_t width = 0; while (width < n && s[width] == s[0]) width++;
    if (width >= ${p.minFence}) return true;
  }
  const uint32_t thematic[] = {${p.thematic.map(cp).join(',')}};
  for (size_t m = 0; m < sizeof(thematic)/sizeof(*thematic); m++) {
    size_t count = 0; bool matches = true;
    for (size_t j = 0; j < n; j++) if (!kio_doc_whitespace(s[j])) { count++; matches &= s[j] == thematic[m]; }
    if (matches && count >= 3) return true;
  }
  if (n > 1 && (${p.list.map(c => `s[0] == ${cp(c)}`).join(' || ')}) && s[1] == 32) return true;
  size_t digits = 0; while (digits < n && s[digits] >= 48 && s[digits] <= 57) digits++;
  return digits && digits+1 < n && (${p.ordered.map(c => `s[digits] == ${cp(c)}`).join(' || ')}) && s[digits+1] == 32;
}
static size_t kio_doc_inline_literal_end(const uint32_t *s, size_t n, size_t start, bool in_heading) {
  if (start >= n) return 0;
  if (s[start] == ${cp(i.escape)} && start+1 < n && kio_doc_ascii_punctuation(s[start+1])) return start+2;
  if (s[start] != ${cp(i.code)}) return 0;
  size_t open = start; while (open < n && s[open] == ${cp(i.code)}) open++;
  size_t a = start; while (a && s[a-1] != 10) a--;
  size_t b = a; while (b < n && s[b] != 10) b++;
  while (a < b && kio_doc_whitespace(s[a])) a++;
  bool heading = in_heading || kio_doc_inline_heading(s+a,b-a);
  for (size_t cursor = open; cursor < n;) {
    if (s[cursor] == ${cp(i.code)}) {
      size_t end = cursor; while (end < n && s[end] == ${cp(i.code)}) end++;
      if (end-cursor == open-start) return end;
      cursor = end;
    } else if (s[cursor] == 10) {
      size_t end = cursor+1; while (end < n && s[end] != 10) end++;
      if (heading || kio_doc_inline_break(s+cursor+1,end-cursor-1)) break;
      cursor++;
    } else cursor++;
  }
  return open;
}
// Conservative chunk boundary: true only after further same-run input cannot
// change this candidate. Run/fence boundaries are supplied by the scanner.
static bool kio_doc_inline_decided(const uint32_t *s, size_t n, bool in_heading, bool line_complete) {
  if (!n) return false;
  if (s[0] == ${cp(i.escape)}) return n >= 2 || line_complete;
  if (s[0] == ${cp(i.code)}) {
    size_t open = 0; while (open < n && s[open] == ${cp(i.code)}) open++;
    size_t end = kio_doc_inline_literal_end(s,n,0,in_heading);
    if (end > open && (end < n || line_complete)) return true;
    if (in_heading && line_complete) return true;
    for (size_t j = 0; j < n; j++) if (s[j] == 10) {
      if (in_heading) return true;
      size_t end_line = j+1; while (end_line < n && s[end_line] != 10) end_line++;
      if ((end_line < n || line_complete) && kio_doc_inline_break(s+j+1,end_line-j-1)) return true;
    }
    return false;
  }
  if (s[0] != ${cp(i.labelOpen)}) return true;
  // Ordinary links have priority and may cross lines. Absence of a closer in
  // a partial buffer is not evidence that the shorter Kiodoc form wins.
  size_t close = 1; while (close < n && s[close] != ${cp(i.labelClose)}) close++;
  if (close == n) return false;
  if (close+1 == n && !line_complete) return false;
  if (close+1 < n && s[close+1] == ${cp(i.destinationOpen)}) {
    return kio_doc_link_bounds(s,n,0).found;
  }
  KioDocBounds bracket = kio_doc_bracket_bounds(s,n,0);
  if (!bracket.found) return true;
  if (!bracket.complete) return bracket.end < n || line_complete;
  size_t after = bracket.end + ${rules.bracket.close.length};
  while (after < n && kio_doc_whitespace(s[after])) after++;
  return after < n;
}
`;
}

export function bracketPattern() {
  const escape = s => s.replace(/[.*+?^\${}()|[\]\\]/g, '\\$&');
  const body = rules.bracket.forbidden.map(c => c === '\n' ? '\\n' : escape(c)).join('');
  return `${escape(rules.bracket.open)}[^${body}]*${escape(rules.bracket.close)}`;
}

export function lexicalPatterns() {
  const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const i = rules.inline;
  const open = escape(rules.bracket.open), close = escape(rules.bracket.close);
  const body = `[^${rules.bracket.forbidden.map(c => c === '\n' ? '\\n' : escape(c)).join('')}]`;
  const ws = `[${rules.whitespace.map(c => `\\u${c.toString(16).padStart(4, '0')}`).join('')}]`;
  return {
    bracketOpen: open, bracketClose: close, bracketBody: body,
    bracketComplete: bracketPattern(), bracketIncomplete: `${open}${body}*(?=\\n|$)`,
    directive: `${escape(rules.bracket.directive)}[A-Za-z]*`, directives: rules.directives.map(([, word]) => word),
    whitespace: ws,
    textmateWhitespace: ws.replaceAll(/\\u([0-9a-f]{4})/g, '\\x{$1}'),
    escape: `${escape(i.escape)}[!-/:-@\\[-\x60{-~]`,
    codeOpen: `(${escape(i.code)}+)`, codeClose: `(?<!${escape(i.code)})\\1(?!${escape(i.code)})`,
    codeMatchedLine: `(?<!${escape(i.code)})(${escape(i.code)}+)(?!${escape(i.code)})[^\\n]*?(?<!${escape(i.code)})\\1(?!${escape(i.code)})`,
    codeUnmatchedRun: `${escape(i.code)}+`,
    link: `${escape(i.labelOpen)}[^${escape(i.labelClose)}]*${escape(i.labelClose)}${escape(i.destinationOpen)}[^${escape(i.destinationClose)}]*${escape(i.destinationClose)}`,
    definition: `${ws}*${escape(i.labelOpen)}(?!${escape(i.code)})[^${escape(i.labelClose)}]*[^${escape(i.labelClose)}${ws.slice(1, -1)}][^${escape(i.labelClose)}]*${escape(i.labelClose)}${ws}*${escape(i.definition)}`,
    specialStarts: [i.escape, i.code, i.labelOpen],
  };
}

export function textmateInlinePatterns() {
  const p = lexicalPatterns();
  p.whitespace = p.textmateWhitespace;
  const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const linkedSuffix = `(?:${escape(rules.inline.destinationOpen)}|${escape(rules.inline.labelOpen)})`;
  const nonspaceBody = `(?:(?!${p.whitespace})${p.bracketBody})`;
  const operand = `(?:${nonspaceBody}(?:${p.bracketBody}*?${nonspaceBody})?)?`;
  const role = {
    1: { name: 'punctuation.definition.kiodoc.kio' },
    2: { name: 'keyword.control.kiodoc.kio' },
    3: { name: 'variable.other.kiodoc.kio' },
    4: { name: 'punctuation.definition.kiodoc.kio' },
  };
  return [
    { match: p.escape, name: 'punctuation.definition.marker.kiodoc.kio' },
    { match: p.codeMatchedLine, name: 'string.unquoted.code.kiodoc.kio' },
    // A line-state engine cannot retract an earlier line's roles when a code
    // span closes later. Keep that ambiguous tail neutral inside the doc run.
    { begin: p.codeOpen, end: '(?!)', name: 'markup.raw.inline.kiodoc.kio' },
    { match: p.link, name: 'markup.underline.link.kiodoc.kio' },
    { match: `(${p.bracketOpen})(?:(${p.directive})${p.whitespace}*)?${p.whitespace}*(${operand})${p.whitespace}*(${p.bracketClose})(?!${p.whitespace}*${linkedSuffix})`, captures: role },
    { match: `(${p.bracketOpen})(?:(${p.directive})${p.whitespace}*)?${p.whitespace}*(${operand})${p.whitespace}*(?=\\n|$)`, captures: role },
  ];
}

export function markupPatterns() {
  const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const p = rules.paragraph;
  const markers = rules.emphasis.map(escape);
  const ws = lexicalPatterns().textmateWhitespace;
  return {
    heading: `${escape(p.heading)}{1,${p.maxHeading}}(?: |$)`,
    list: `(?:${p.list.map(escape).join('|')}|[0-9]+(?:${p.ordered.map(escape).join('|')})) `,
    quote: `${escape(p.quote)} ?`,
    thematic: `(?:${p.thematic.map(c => `(?:${ws}*${escape(c)}${ws}*){3,}`).join('|')})`,
    strong: markers.map(m => `${m}${m}(?:(?!${m}${m}).)*${m}${m}`),
    emphasis: markers.map(m => `${m}[^${m} ][^${m}]*${m}`),
    kioLanguage: rules.kioLanguage,
    roles: {
      heading: 'comment.doc.heading', strong: 'comment.doc.strong',
      emphasis: 'comment.doc.emphasis', marker: 'comment.doc.marker',
      link: 'comment.doc.link', attribute: 'comment.doc.attribute',
    },
  };
}

const self = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === self) {
  const root = path.resolve(path.dirname(self), '../..');
  const formatted = spawnSync('rustfmt', ['--edition', '2024'], { input: rustRules(), encoding: 'utf8' });
  if (formatted.status !== 0) throw new Error(formatted.stderr || 'rustfmt failed');
  const outputs = [
    ['kio-rs/src/doc_markup/generated.rs', formatted.stdout],
    ['tools/tree-sitter-kio/src/doc_rules.h', cRules()],
  ];
  if (process.argv[2] === '--check') {
    for (const [output, content] of outputs) {
      if (fs.readFileSync(path.join(root, output), 'utf8') !== content) {
        throw new Error(`Kiodoc rules are stale: ${output}; run node tools/kiodoc-grammar/generate.mjs`);
      }
    }
  } else if (process.argv.length === 2) {
    for (const [output, content] of outputs) fs.writeFileSync(path.join(root, output), content);
  } else {
    throw new Error('usage: node tools/kiodoc-grammar/generate.mjs [--check]');
  }
}
